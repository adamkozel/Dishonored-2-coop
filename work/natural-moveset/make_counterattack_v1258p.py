"""1258p (#9, 1214ap): Test-Counterattack-v1258o.ps1 with the lab health hold instead of the native god mode, and a
provocation. ark_god_player never protected the source (1258ai: 56 -> 0; confirmed static, retail damage code never reads
it), so -HealthHold turns coop_player_health_hold on from arming until restoration. A passive guard never swings
(1258ac-1258ae, 1258aj, 1258ak), so the first cycle opens with two slashes; afterwards the source only taps block and
attacks after sword_parry_win, so a finisher right after a parry win is the counter-kill."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258o.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258af',[string]$Candidate='candidate-npc-combat-v1214ao',[switch]$God",
    "[string]$Take='counterattack-v1258al',[string]$Candidate='candidate-npc-combat-v1214ap',[switch]$God,[switch]$HealthHold")
rep("# 1258o (#9, 1214ao): -God", "# 1258p (#9, 1214ap): -HealthHold (lab coop_player_health_hold) and a two-slash provocation. Generated by\n# make_counterattack_v1258p.py.\n# 1258o (#9, 1214ao): -God")
rep("   if($God){C $source 'ark_god_player 1';$row.god=$true};",
    "   if($HealthHold){C $source 'coop_player_health_hold on';$row.healthHold=$true};")
rep("if($God){try{C $source 'ark_god_player 0'}catch{}}",
    "if($HealthHold){try{$row.healthHoldStatus=(S $source '.observer-camera.json').healthHold;C $source 'coop_player_health_hold off'}catch{}}")
rep("""    if($kind-eq'counter'){if(!$row.counterStarted){$row.counterStarted=$true;Start-Sleep -Milliseconds 2000}""",
    """    if($kind-eq'counter'){if(!$row.counterStarted){$row.counterStarted=$true;Start-Sleep -Milliseconds 2000
      foreach($n in 1,2){& "$lab/Send-D2Input.ps1" -Role $source -RightTrigger 255 -DurationMs 200|Out-Null;Start-Sleep -Milliseconds 700}}""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258p.ps1').write_bytes(out.encode('utf-8'))
print('ok')
