"""1577 (#11 enemy_body_size_variants, seated): Record-MissionCoverage-v1573.ps1 with -PressWhenReady: from 250 ms the source's
takedown sensor is read every loop (probe --takedown-sensor, 1214es) and the choke press (RightShoulder held 6.5 s, written
directly) goes in at the first sample where the sensor is ready (+0x1dd) and its choke entry (1, the slot-10 assassination
sensor's target) holds an available target (state 3); the crouched creep is skipped once pressed. In 1575a the seated
servant was ready from 0.38 s, but the press came at 1.9 s, after she had noticed Corvo (state 4), and became a parry.
Generated by make_mission_coverage_v1577.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1573.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[double]$PrebindOffset=0)", "[double]$PrebindOffset=0,[switch]$PressWhenReady)")
first = s.index('\n') + 1
s = s[:first] + "# 1577 (#11): -PressWhenReady presses the choke at the first ready takedown-sensor sample. Generated by make_mission_coverage_v1577.py.\n" + s[first:]
creep = "   if($CrouchApproach-and!$row.crept-and$t-ge(650+$delay)){"
rep(creep,
    "   if($PressWhenReady-and!$acted-and$t-ge250){$pr=try{Q $source '--takedown-sensor'}catch{$null};$pe=@(if($pr){$pr.entries}else{@()})\n"
    "    if($pr-and$pr.ready1dd-and$pe.Count-gt1-and$pe[1].dwords[13]-eq3){& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder -DurationMs 6500|Out-Null\n"
    "     $acted=[pscustomobject]@{direct=$true};$row.actedAt=$t;$row.pressedWhenReady=[ordered]@{t=$t;name=$pe[1].name;state=$pe[1].dwords[13]}}}\n"
    "   if($CrouchApproach-and!$row.crept-and!$acted-and$t-ge(650+$delay)){")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1577.ps1').write_bytes(out.encode('utf-8'))
print('ok')
