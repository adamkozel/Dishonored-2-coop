"""Derives Test-HelloFollow-v1278.ps1 from Test-PairedVictim-v1248l.ps1 (product controller on the Dunwall fixture,
checkpoint restoration) for stage 4 (#14): the Hello follow (1214o) at runtime. With the product controller armed and both
combat sessions active, NPC combat is turned off on both peers; the host then applies lab-only host-world damage
(coop_npc_combat hostworld_test, 1214af: a stream-bound target when combat is off) to the Dunwall tutorial guard, so only
the host's guard loses health outside any combat channel. Combat is turned back on: at re-binding the host's Hello carries
the lower health. Pass (runtime): the divergence exists before re-binding, the client follows (helloFollowed) and the guard
health is equal in both worlds with the session active again."""
from pathlib import Path
P = Path(__file__).resolve().parent
s = P.joinpath('Test-PairedVictim-v1248l.ps1').read_bytes().decode('utf-8'); nl = '\r\n' if '\r\n' in s else '\n'
lines = s.split(nl)
def idx(prefix, start=0):
    for i in range(start, len(lines)):
        if lines[i].startswith(prefix): return i
    raise AssertionError(prefix)
main = idx('try{'); tail = idx('}catch{$failure=$_.Exception.Message;Save "$out/failure.json"')
head = lines[:main]
head[0] = "param([ValidatePattern('^[a-z0-9-]+$')][string]$Take='hello-follow-v1278a',[string]$Candidate='candidate-npc-combat-v1214af')"
head = [head[0], '# 1278 (stage 4, #14, 1214af): the Hello follow at runtime. Generated by make_hello_follow_v1278.py from 1248l.'] + [l for l in head[1:] if not l.startswith('# ')]
setup = lines[main:idx(' foreach($source in $Sources)')]
setup = [l.replace("operation='PairedVictim1248l'", "operation='HelloFollow1278'").replace('sources=$Sources', 'test=$Take') for l in setup]
body = r''' $row=[ordered]@{passed=$false;failure=$null;checks=[Collections.Generic.List[string]]::new()}
 try{
  $dirty=$true;Arm
  foreach($q in 'host','client'){C $q 'setviewpos -33 -153 68.1 90 0'}
  $live=WaitLive 'armed' 45000;if(!$live.ok){throw 'Partner presentation not live after arming'}
  $active={$w=[Diagnostics.Stopwatch]::StartNew();do{Start-Sleep -Milliseconds 400;$hc=S host '.npc-combat.json';$cc=S client '.npc-combat.json';$ok=$hc.result-eq'active_native_melee'-and$cc.result-eq'active_native_melee'}while(!$ok-and$w.ElapsedMilliseconds-lt20000);$ok}
  if(!(& $active)){throw 'Combat session not active on both peers'};$row.checks.Add('Combat session active on both peers')
  $g=Guard host;$og=Guard client;$row.guardHost=$g.handle;$row.guardClient=$og.handle
  C host ('setviewpos {0} {1} {2} 0 0' -f (F ([double]$g.position[0]-1.8)),(F ([double]$g.position[1])),(F ([double]$g.position[2]+1.7)));Start-Sleep -Milliseconds 700
  $health={[ordered]@{host=(Q host '--health' $g.handle).current;client=(Q client '--health' $og.handle).current}}
  $before=& $health;$followed0=(S client '.npc-combat.json').helloFollowed
  foreach($q in 'host','client'){C $q 'coop_npc_combat off'};$w=[Diagnostics.Stopwatch]::StartNew()
  do{Start-Sleep -Milliseconds 300;$off=!(S host '.npc-combat.json').enabled-and!(S client '.npc-combat.json').enabled}while(!$off-and$w.ElapsedMilliseconds-lt5000)
  if(!$off){throw 'NPC combat did not turn off'};$row.checks.Add('NPC combat off on both peers')
  C host 'coop_npc_combat hostworld_test';Start-Sleep -Milliseconds 1500;$t=S host '.npc-hostworld-test.json'
  $mid=& $health;$row.before=$before;$row.mid=$mid;$row.test=$t
  if($t.result-ne'damaged'-or$t.target-ne$g.handle){throw "Host-only damage not applied to the guard ($($t.result), target $($t.target))"}
  if(!([double]$mid.host-lt[double]$before.host)-or$mid.client-ne$before.client){throw "No host-only divergence (host $($before.host) -> $($mid.host), client $($before.client) -> $($mid.client))"}
  $row.checks.Add("Host-only loss outside combat: host $($before.host) -> $($mid.host), client stays $($mid.client)")
  foreach($q in 'host','client'){C $q 'coop_npc_combat on'}
  $w=[Diagnostics.Stopwatch]::StartNew();$timeline=[Collections.Generic.List[object]]::new()
  do{Start-Sleep -Milliseconds 500;$h=& $health;$hc=S host '.npc-combat.json';$cc=S client '.npc-combat.json'
   $timeline.Add([pscustomobject]@{ms=$w.ElapsedMilliseconds;host=$h.host;client=$h.client;hostResult=$hc.result;clientResult=$cc.result;helloFollowed=$cc.helloFollowed;helloWaited=$hc.helloWaited;followSubtractions=$cc.followSubtractions})
   $done=$h.host-eq$h.client-and$hc.result-eq'active_native_melee'-and$cc.result-eq'active_native_melee'}while(!$done-and$w.ElapsedMilliseconds-lt20000)
  Save "$out/rebind.json" @($timeline);$after=& $health;$row.after=$after
  foreach($q in 'host','client'){foreach($suffix in '.npc-stream.json','.npc-combat.json','.npc-hostworld-test.json'){try{Copy-Item -LiteralPath "$root/work/lab-instances/$q/coop-status.json$suffix" -Destination "$out/$q$suffix" -ErrorAction Stop}catch{}}}
  $cc=S client '.npc-combat.json';$row.helloFollowed=$cc.helloFollowed-$followed0
  if($after.host-ne$after.client){throw "Guard health differs after re-binding (host $($after.host), client $($after.client))"}
  if($row.helloFollowed-lt1){throw 'The client did not follow a host Hello'}
  $row.checks.Add("Re-binding: the client followed the host Hello ($($row.helloFollowed)); guard $($after.host) in both worlds")
  $row.passed=$true
 }catch{$row.failure=$_.Exception.Message}
 try{foreach($q in 'host','client'){C $q 'coop_npc_combat on'}}catch{}
 try{Restore 'hello';$row.restored=$true}catch{$row.restored=$false;$row.failure=(("$($row.failure); restore: "+$_.Exception.Message)).TrimStart('; ')}
 $rows.Add([pscustomobject]$row);Save "$out/hello.json" ([pscustomobject]$row)
 if(!$row.restored){throw 'Fixture restore failed'}
 $dirty=$false'''
end = [l.replace("operation='PairedVictim1248l'", "operation='HelloFollow1278'") for l in lines[tail:]]
out = nl.join(head + setup + body.split('\n') + end)
def rep(old, new):
    global out
    assert out.count(old) == 1, old[:70]; out = out.replace(old, new)
rep("scope='paired_victim_alignment: rear choke under the product controller (NPC stream on, natural guard AI), both source roles; partner phases and the observer-world victim recorded; fixture restored after every case.'",
    "scope='Stage 4 Hello follow: with NPC combat off on both peers the host takes a host-only health loss on the Dunwall tutorial guard (lab hostworld_test); at re-binding the client must follow the host Hello to the same health; fixture restored.'")
rep('"PASS_PAIRED_VICTIM $($rows.Count) cases"', '"PASS_HELLO_FOLLOW"')
rep('$failure="$($bad.Count) case(s) failed: "+(($bad|ForEach-Object {"$($_.source)-$($_.kind): $($_.failure)"})-join \' | \')', '$failure=($bad|ForEach-Object {$_.failure})-join \' | \'')
P.joinpath('Test-HelloFollow-v1278.ps1').write_bytes(out.encode('utf-8'))
print('ok')
