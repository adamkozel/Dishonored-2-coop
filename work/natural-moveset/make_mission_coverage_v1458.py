"""1458 (#11 wall_and_window_variants): Record-MissionCoverage-v1448.ps1 with the takedown target placed at a window. The game
has window takedowns for both kinds and four directions (midnight/gameplay/player/base/assassination/
assassination_window_{back,front,left,right} and choke/choke_window_*, plus carry-corpse variants; confirmed static).
Edge of the World has a crossable window, script_rich_small_01_sndctrl at (16.22, 90.63, 17.51), with a floor on both sides
(probe 1231b, crossed in 1235i). -PlaceAt x,y,z,yaw stands the target there first through the lab-only
coop_lab_npc_place (host), and -Behind sets the source's distance behind it (0.9 m by default), so the source stands on the
near side of the sill and the target just past it. The scene watch records which takedown scene the game chose.
Generated by make_mission_coverage_v1458.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1448.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[ValidateSet('choke','lethal')][string]$TakedownKind='choke')",
    "[ValidateSet('choke','lethal')][string]$TakedownKind='choke',[string]$PlaceAt='',[double]$Behind=0.9)")
first = s.index('\n') + 1
s = s[:first] + "# 1458 (#11): -PlaceAt stands the takedown target (window fixture); -Behind sets the source's distance. Generated by make_mission_coverage_v1458.py.\n" + s[first:]
rep("     $tg=@(Living $source|Where-Object {$_.spawnerName-eq$TargetSpawner-and$_.unique})\n     if(!$tg.Count){throw \"Target $TargetSpawner is not on the map\"}",
    "     if($PlaceAt){$pa=@($PlaceAt-split','|ForEach-Object {[double]$_});if($pa.Count-ne4){throw 'PlaceAt needs x,y,z,yaw'}\n"
    "      C host ('coop_lab_npc_place {0} {1} {2} {3} {4}' -f $TargetSpawner,$pa[0].ToString('F3',$inv),$pa[1].ToString('F3',$inv),$pa[2].ToString('F3',$inv),$pa[3].ToString('F2',$inv));Start-Sleep -Milliseconds 700\n"
    "      $row.placed=try{(S host '.observer-camera.json').labNpcPlace}catch{$null};if($row.placed.result-ne'placed'){throw \"Target placement refused ($($row.placed.result))\"}}\n"
    "     $tg=@(Living $source|Where-Object {$_.spawnerName-eq$TargetSpawner-and$_.unique})\n     if(!$tg.Count){throw \"Target $TargetSpawner is not on the map\"}")
for v in ('fx', 'fy', 'gx', 'gy'):
    rep(f"0.9*${v}", f"$Behind*${v}")
rep("     $expected=if($HitAt){'alive'}",
    "     $row.windowScenes=@(Get-Content \"$out/$key-midnight.ndjson\" -ErrorAction SilentlyContinue|Select-String -Pattern '(assassination|choke)_window_[a-z_]+' -AllMatches|ForEach-Object {$_.Matches.Value}|Sort-Object -Unique)\n"
    "     if($PlaceAt){$row.checks.Add(\"Window fixture: target placed $($row.placed.result); takedown scenes $(@($row.windowScenes)-join ', ')\")}\n"
    "     $expected=if($HitAt){'alive'}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1458.ps1').write_bytes(out.encode('utf-8'))
print('ok')
