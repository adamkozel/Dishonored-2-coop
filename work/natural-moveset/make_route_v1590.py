"""1590 (#102): Route-Mission-v1300.ps1 whose 'at' and 'use' steps take an optional "role" (default host), so the
client can stand and use a world entity in its own world, e.g. pick up its own Timepiece in A Crack in the Slab
(pr_a_ld_timeshift_device_pickup_1). In route-bk-timepiece-v1589a only the host picked it up, and the two-account take
campaign-bunker-vm-v1307a never had the joiner act, so whether Emily can hold a Timepiece of her own was never tested.
A 'use' with a role reads that role's entities, snapshots, focus sensor and input; the step's other rules are unchanged.
Generated by make_route_v1590.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Route-Mission-v1300.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1590 (#102): 'at' and 'use' steps take an optional role. Generated by make_route_v1590.py.\n" + s[first:]
rep("function Ents(){for($k=0;$k-lt6;$k++){try{return (Q host '--entities').entities}catch{[void](Settle 'entities' 60);Start-Sleep 2}};throw 'Native query failed host --entities'}",
    "function Ents($r='host'){for($k=0;$k-lt6;$k++){try{return (Q $r '--entities').entities}catch{[void](Settle 'entities' 60);Start-Sleep 2}};throw \"Native query failed $r --entities\"}")
# Each step names its acting role up front; 'press' and 'die' already read $st.role the same way.
rep("  if($st.unlessMap-and\"$((Snap host).map)\"-match$st.unlessMap){$notes.skipped+=@($tag);continue};$ents=Ents\n",
    "  if($st.unlessMap-and\"$((Snap host).map)\"-match$st.unlessMap){$notes.skipped+=@($tag);continue};$who=if($st.role){$st.role}else{'host'};$ents=Ents $who\n")
rep("   'at'{C host (\"setviewpos {0:F3} {1:F3} {2:F3} {3:F2} 0\"-f$st.pos[0],$st.pos[1],$st.pos[2],$(if($st.yaw){$st.yaw}else{0}))}\n",
    "   'at'{C $who (\"setviewpos {0:F3} {1:F3} {2:F3} {3:F2} 0\"-f$st.pos[0],$st.pos[1],$st.pos[2],$(if($st.yaw){$st.yaw}else{0}))}\n")
rep("   'at'{C host (\"setviewpos {0:F3} {1:F3} {2:F3} {3:F2} 0\"-f$st.pos[0],$st.pos[1],$st.pos[2],$st.yaw);Start-Sleep -Milliseconds 700;if($st.pitch){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role host -Pitch $st.pitch -Quick|Out-Null}catch{}}}\n",
    "   'at'{C $who (\"setviewpos {0:F3} {1:F3} {2:F3} {3:F2} 0\"-f$st.pos[0],$st.pos[1],$st.pos[2],$st.yaw);Start-Sleep -Milliseconds 700;if($st.pitch){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $who -Pitch $st.pitch -Quick|Out-Null}catch{}}}\n")
a = s.index("   'use'{$e=if($st.match)")
b = s.index("    if(!$hit){throw \"Use of $($st.name) not registered\"}}\n", a)
block = s[a:b]
n0 = block.count(' host ') + block.count('(Snap host)') + block.count('-Role host')
for old, new in (("Q host ", "Q $who "), ("C host ", "C $who "), ("Snap host", "Snap $who"), ("Frame host ", "Frame $who "),
                 ("I host ", "I $who "), ("-Role host ", "-Role $who "), ('throw "Host died', 'throw "$who died')):
    block = block.replace(old, new)
assert 'host' not in block.replace('Host', ''), [l for l in block.split('\n') if 'host' in l]
s = s[:a] + block + s[b:]
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Route-Mission-v1590.ps1').write_bytes(out.encode('utf-8'))
print('ok', n0)
