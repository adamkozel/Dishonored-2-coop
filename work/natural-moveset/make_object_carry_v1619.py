"""1619 (#115): Probe-ObjectCarry-v1618.ps1 with a Far Reach timeline. In object-carry-v1618a Emily's pulled bottle
shattered on arrival (her film), yet her held tracker counted two pulls, one break and a final settle, and Corvo's copy
never broke. The farreachbottle case now records, per sample, the held-object status of both worlds and the bottle's
life in each world: whether its handle still resolves and the current value of its own health component (found once
before the pull with --components, read with --object +0x20, the low 4 bytes of the word; v1619a converted it wrong). The power-state dumps (already recorded in 1616b) are off,
which keeps the sampling fast. Generated by make_object_carry_v1619.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Probe-ObjectCarry-v1618.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1619 (#115): farreachbottle traces held status and the bottle's life in both worlds. Generated by make_object_carry_v1619.py.\n" + s[first:]
# the bottle's health component in both worlds, found before the input
rep("Save \"$out/$key-near-before.json\" $near0}",
    "Save \"$out/$key-near-before.json\" $near0\n"
    "    $hcp=@{};foreach($q in 'host','client'){$hcp[$q]=try{@((Q $q '--components' $target[0].handle).components|Where-Object {$_.vtableRva-in'0x1c51268','0x1c51588'})[0].pointer}catch{$null}};$row.healthComponents=$hcp}")
# held status of both worlds every sample, and the bottle's life after 2.8 s
rep("    if($case.name-in'heldbottle','placebottle'){$hs=",
    "    if($case.name-eq'farreachbottle'-and$watch.ElapsedMilliseconds-ge2800){$lv=[ordered]@{ms=$watch.ElapsedMilliseconds}\n"
    "     foreach($q in 'host','client'){$null=& \"$lab/bin/d2_runtime_probe.exe\" $pids[$q] '--components' $target[0].handle;$alive=!$LASTEXITCODE;$lh=$null\n"
    "      if($alive-and$hcp[$q]){$lw=try{(& \"$lab/bin/d2_runtime_probe.exe\" $pids[$q] '--object' $hcp[$q]|ConvertFrom-Json).words[4].word}catch{$null}\n"
    "       if($lw){$lh=[Math]::Round([BitConverter]::ToSingle([BitConverter]::GetBytes([Convert]::ToUInt64(($lw-replace'^0x',''),16)),0),3)}}\n"
    "      $lv[$q]=[ordered]@{alive=$alive;health=$lh}};$lifeTrace.Add([pscustomobject]$lv)}\n"
    "    if($case.name-in'heldbottle','placebottle','farreachbottle'){$hs=")
rep("     if($heldNear.Count-lt2-and", "     if($case.name-ne'farreachbottle'-and$heldNear.Count-lt2-and")
rep("$heldNear=[Collections.Generic.List[object]]::new()",
    "$heldNear=[Collections.Generic.List[object]]::new();$lifeTrace=[Collections.Generic.List[object]]::new()")
rep("if($case.name-eq'farreachbottle'-and$holdDumps.Count-lt14){", "if($case.name-eq'farreachbottle'-and$holdDumps.Count-lt0){")
# the timeline check
rep("    if(!$row.pullState){throw 'No native pull (state 84)'}",
    "    Save \"$out/$key-held.json\" @($heldTrace);Save \"$out/$key-life.json\" @($lifeTrace)\n"
    "    $seq={param($xs)$o=@();foreach($x in $xs){if(!$o.Count-or$o[$o.Count-1]-ne$x){$o+=$x}};,$o}\n"
    "    $srcSeq=& $seq @($heldTrace|ForEach-Object {\"$($_.src.phase)\"});$obsSeq=& $seq @($heldTrace|ForEach-Object {\"$($_.obs.remotePhase)/$($_.obs.result)\"});$fin=$heldTrace[$heldTrace.Count-1]\n"
    "    $row.heldTimeline=[ordered]@{source=$srcSeq;observer=$obsSeq;final=$fin}\n"
    "    $lifeText=foreach($q in 'client','host'){$dead=@($lifeTrace|Where-Object {$_.$q.health-ne$null-and$_.$q.health-le0});$gone=@($lifeTrace|Where-Object {!$_.$q.alive})\n"
    "     \"$q health $(@($lifeTrace|ForEach-Object {$_.$q.health}|Where-Object {$_-ne$null}|Select-Object -First 1)) first zero $(if($dead.Count){$dead[0].ms}else{'never'}) ms, unresolved from $(if($gone.Count){$gone[0].ms}else{'never'}) ms\"}\n"
    "    $row.checks.Add(\"Far Reach timeline: source phases $($srcSeq-join '>'), pulls $($fin.src.pulls), breaks $($fin.src.breaks), settles $($fin.src.settles); observer $($obsSeq-join ' > '), broken $($fin.obs.broken); $($lifeText-join '; ')\")\n"
    "    if(!$row.pullState){throw 'No native pull (state 84)'}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Probe-ObjectCarry-v1619.ps1').write_bytes(out.encode('utf-8'))
print('ok')
