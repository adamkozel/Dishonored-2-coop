    "$row.checks.Add(\"Lab hit $($row.labHit.result): source states $($row.sourceStates-join ', '); presented stun variants $($row.stunVariants-join ',')\")\n"
    "      $stunned=@($row.sourceStates|Where-Object {$_-match'(^|, )1[46]@'}).Count;$shown=@($samples|Where-Object {[double]$_.stunWeight-gt.5})\n"
