"""1462 (#11 power_upgrade_variants): Record-Coverage-v1461.ps1 with Doppelganger Transposition's swap. 1456b: the native
prompt "Swap with Doppelganger" shows the power trigger, but the harness's second press held the trigger 700 ms and cast a
new shade (cast_in, cast_loop, cast_out again, then the old shade's doppelganger_dispawn). The swap press is now a 150 ms
tap. Upgrade cases also record the source's position with every state sample, and the verdict records how far the
source moved (a swap moves it to the shade). Generated by make_coverage_v1462.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1461.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1462 (#11): the Transposition swap as a 150 ms tap; upgrade cases trace the source position. Generated by make_coverage_v1462.py.\n" + s[first:]
rep("@(3200,'lt',700),@(6500,'lt',700));", "@(3200,'lt',700),@(6500,'lt',150));")
rep("$manaTrace.Add([pscustomobject]@{ms=$t;active=@($kps.active|ForEach-Object {'{0}@{1}' -f $_.id,$_.vtable})})}",
    "$manaTrace.Add([pscustomobject]@{ms=$t;active=@($kps.active|ForEach-Object {'{0}@{1}' -f $_.id,$_.vtable});pos=$(if($case-like'upg*'){try{(Q $source '--player').candidatePosition}catch{$null}}else{$null})})}")
rep("      $row.powerVariants=Shown 'powerWeight' 'powerVariant';$row.teleportCount=@($teleports).Count\n",
    "      $row.powerVariants=Shown 'powerWeight' 'powerVariant';$row.teleportCount=@($teleports).Count\n"
    "      $pp=@($manaTrace|Where-Object {$_.pos});$row.sourceMovedMax=$(if($pp.Count){[Math]::Round(($pp|ForEach-Object {[Math]::Sqrt([Math]::Pow([double]$_.pos[0]-[double]$pp[0].pos[0],2)+[Math]::Pow([double]$_.pos[1]-[double]$pp[0].pos[1],2))}|Measure-Object -Maximum).Maximum,2)}else{$null})\n"
    "      $row.checks.Add(\"Source moved at most $($row.sourceMovedMax) m from its first traced position\")\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-Coverage-v1462.ps1').write_bytes(out.encode('utf-8'))
print('ok')
