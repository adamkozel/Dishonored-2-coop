"""1534 (#11 enemy_body_size_variants, seated): Record-MissionCoverage-v1533.ps1 with -WaitSitting: once the target is
chosen, the host's NPCs are read with the native seated test's own input (probe --sitting, 1214em: a type-1 navigation
request) every 0.5 s for up to 90 s, and the source is stood only when the target counts as seated (1512a/b and 1516a/b:
the office guard was standing or in a conversation at the press; 1524b: a sleeper in an armchair is not seated). The
seated state is read again just before the press, on the source and on the host, and saved in the row.
Generated by make_mission_coverage_v1534.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1533.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$KnockOnGround,[switch]$WindowProbe)", "[switch]$KnockOnGround,[switch]$WindowProbe,[switch]$WaitSitting)")
first = s.index('\n') + 1
s = s[:first] + "# 1534 (#11): -WaitSitting waits until the target counts as seated natively. Generated by make_mission_coverage_v1534.py.\n" + s[first:]
anchor = "$row.target=[ordered]@{spawner=$TargetSpawner;definition=$tg[0].definition;position=$np;forward=@($fx,$fy)};$row.kind=$TakedownKind\n"
rep(anchor, anchor +
    "     if($WaitSitting){$ws2=[Diagnostics.Stopwatch]::StartNew();$row.sittingWait=$null\n"
    "      do{$sq=try{Q host '--sitting'}catch{$null};$me=@($sq.npcs|Where-Object {$_.spawnerName-eq$TargetSpawner});if($me.Count-and$me[0].sitting){$row.sittingWait=[ordered]@{ms=$ws2.ElapsedMilliseconds;requests=$me[0].requests;position=$me[0].position}}else{Start-Sleep -Milliseconds 500}\n"
    "      }while(!$row.sittingWait-and$ws2.ElapsedMilliseconds-lt90000)\n"
    "      if(!$row.sittingWait){throw \"The target never counted as seated (no type-1 navigation request) within 90 s\"}\n"
    "      $tg=@(Living $source|Where-Object {$_.spawnerName-eq$TargetSpawner-and$_.unique});$np=$tg[0].position;$o=$tg[0].orientation;$fx=[double]$o[0];$fy=[double]$o[1];$fl=[Math]::Max(.1,[Math]::Sqrt($fx*$fx+$fy*$fy));$fx/=$fl;$fy/=$fl}\n")
press = "      if(!$acted-and$t-ge(700+$delay)-and(!$KnockdownSettle-or$t-ge4400)){"
rep(press, "      if($WaitSitting-and!$acted-and!$row.sittingAtPress-and$t-ge(600+$delay)){$sq=try{Q $source '--sitting'}catch{$null};$me=@($sq.npcs|Where-Object {$_.spawnerName-eq$TargetSpawner});$hq=try{Q host '--sitting'}catch{$null};$he=@($hq.npcs|Where-Object {$_.spawnerName-eq$TargetSpawner});$row.sittingAtPress=[ordered]@{t=$t;source=$(if($me.Count){[bool]$me[0].sitting}else{$null});sourceRequests=$(if($me.Count){$me[0].requests}else{$null});host=$(if($he.Count){[bool]$he[0].sitting}else{$null})}}\n" + press)
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1534.ps1').write_bytes(out.encode('utf-8'))
print('ok')
