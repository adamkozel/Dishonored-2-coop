"""1258o (#9, 1214ao): Test-Counterattack-v1258n.ps1 with -God. The source's native player invulnerability
(ark_god_player, lab console only) is on from arming until restoration, so the fight continues until a parry win comes
(1258m/1258n/1258y: the client died before any counter). The source's player health is recorded before and after."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258n.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258ac',[string]$Candidate='candidate-npc-combat-v1214ak'",
    "[string]$Take='counterattack-v1258af',[string]$Candidate='candidate-npc-combat-v1214ao',[switch]$God")
rep("# 1258n (#9, 1214ak): native counter-kill",
    "# 1258o (#9, 1214ao): -God keeps the source invulnerable (ark_god_player) from arming to restoration. Generated by\n"
    "# make_counterattack_v1258o.py.\n# 1258n (#9, 1214ak): native counter-kill")
rep("   $dirty=$true;Arm\n",
    "   $dirty=$true;Arm\n   if($God){C $source 'ark_god_player 1';$row.god=$true};$row.sourceHealthStart=try{(Q $source '--health' 1).current}catch{$null}\n")
rep("  try{Restore $key;$row.restored=$true}",
    "  $row.sourceHealthEnd=try{(Q $source '--health' 1).current}catch{$null};if($God){try{C $source 'ark_god_player 0'}catch{}}\n  try{Restore $key;$row.restored=$true}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258o.ps1').write_bytes(out.encode('utf-8'))
print('ok')
