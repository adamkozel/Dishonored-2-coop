"""1254t (#11 ragdoll_handoff): Test-TakedownVariants-v1254q.ps1 whose corpse release also covers the client-sourced kill.
The host owns every corpse natively; only the client holds its corpse animated at the host's pose and releases it to
native physics when its channel stops. With a host source that is the observer (1254o, filmed); with a client source it
is the source itself, whose camera looked along the corridor in 1254p. -CorpseRelease now samples the corpse in both
worlds and, for a client source, pitches the source's view 50 degrees down before the release so its own video shows the
corpse. Generated by make_takedown_variants_v1254t.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-TakedownVariants-v1254q.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

rep("# 1254q (#11):", "# 1254t (#11 ragdoll_handoff): the release samples both worlds; a client source looks down at its own held corpse.\n# Generated by make_takedown_variants_v1254t.py.\n# 1254q (#11):")
rep("   if($CorpseRelease-and$kind-eq'lethal'){$rel=[Collections.Generic.List[object]]::new();$rw=[Diagnostics.Stopwatch]::StartNew();$released=$false\n",
    "   if($CorpseRelease-and$kind-eq'lethal'){$rel=[Collections.Generic.List[object]]::new();$rw=[Diagnostics.Stopwatch]::StartNew();$released=$false\n"
    "    if($source-eq'client'){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $source -Pitch 50 -Quick|Out-Null}catch{}}\n")
rep("     $rel.Add([pscustomobject]@{ms=$rw.ElapsedMilliseconds;released=$released;position=$og.position;entry=$e2.result;corpse=$e2.corpse;enabled=$e2.enabled});Start-Sleep -Milliseconds 100}\n",
    "     $sg=try{Guard $source}catch{$null};$ns3=try{S $source '.npc-stream.json'}catch{$null};$e3=if($ns3){@($ns3.entries|Where-Object {$_.handle-eq$row.guardHandleSource})|Select-Object -First 1}else{$null}\n"
    "     $rel.Add([pscustomobject]@{ms=$rw.ElapsedMilliseconds;released=$released;position=$og.position;entry=$e2.result;corpse=$e2.corpse;enabled=$e2.enabled;sourcePosition=$sg.position;sourceEntry=$e3.result});Start-Sleep -Milliseconds 100}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-TakedownVariants-v1254t.ps1').write_bytes(out.encode('utf-8'))
print('ok')
