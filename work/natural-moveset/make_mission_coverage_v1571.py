"""1571 (#11 enemy_body_size_variants, seated): Record-MissionCoverage-v1569.ps1 with -TakedownProbe: the player's takedown
sensor (probe --takedown-sensor, 1214es: mode +0x1d8, ready +0x1dd and its five target entries) is read every loop from
250 ms until one sample after the press and saved per case (<key>-takedown-sensor.json; the row keeps takedownAtPress).
1567b/1568a: the seated servant was the interaction sensor's target, but never the choke sensor's, whose picker needs
the takedown sensor ready with that NPC (chapter 100).
Generated by make_mission_coverage_v1571.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1569.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$ClientPrebind)", "[switch]$ClientPrebind,[switch]$TakedownProbe)")
first = s.index('\n') + 1
s = s[:first] + "# 1571 (#11): -TakedownProbe samples the player's takedown sensor until the press. Generated by make_mission_coverage_v1571.py.\n" + s[first:]
rep("$chokes=[Collections.Generic.List[object]]::new();", "$chokes=[Collections.Generic.List[object]]::new();$tdsens=[Collections.Generic.List[object]]::new();")
anchor = "      if($ChokeProbe-and$t-ge250-and(!$acted-or!$row.chokeAfter)){"
rep(anchor,
    "      if($TakedownProbe-and$t-ge250-and(!$acted-or!$row.takedownAfter)){$ts=try{Q $source '--takedown-sensor'}catch{$null}\n"
    "       if($ts){$tdsens.Add([ordered]@{t=$t;acted=[bool]$acted;mode=$ts.mode;active=$ts.active;ready=$ts.ready1dd;bytes=$ts.bytes1dc;word1e4=$ts.word1e4;entries=$ts.entries})\n"
    "        if($acted){$row.takedownAfter=$t}else{$row.takedownAtPress=[ordered]@{t=$t;mode=$ts.mode;active=$ts.active;ready=$ts.ready1dd;names=@($ts.entries|ForEach-Object {$_.name})}}}}\n" + anchor)
rep('if($ChokeProbe){Save "$out/$key-choke.json" @($chokes);',
    'if($TakedownProbe){Save "$out/$key-takedown-sensor.json" @($tdsens);$row.takedownSamples=$tdsens.Count}\n     if($ChokeProbe){Save "$out/$key-choke.json" @($chokes);')
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1571.ps1').write_bytes(out.encode('utf-8'))
print('ok')
