"""1423 (#11 carry_body_lift_idle_move_drop_throw): Test-CarryBody-v1277r.ps1 with -Throw. On 1214dv the product body carry
attaches in both roles (1277y Corvo on the client, 1277z Emily on the host): pickup, walk and drop. With -Throw the end of
the carry walk throws the body (RT, the native high throw, carry variant 8) instead of dropping it (X), so the throw is
recorded in product mode. Generated by make_carry_body_v1423.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1277r.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[int]$KillAttempts=15)", "[int]$KillAttempts=15,[switch]$Throw)")
first = s.index('\n') + 1
s = s[:first] + "# 1423 (#11): -Throw ends the carry walk with the native throw (RT) instead of the drop. Generated by make_carry_body_v1423.py.\n" + s[first:]
rep("   I $source X 900;Start-Sleep -Milliseconds 3000;$carryRows.Add((& $bodyAt 'dropped'))",
    "   if($Throw){& \"$lab/Send-D2Input.ps1\" -Role $source -RightTrigger 255 -DurationMs 250|Out-Null;$row.released='throw'}else{I $source X 900;$row.released='drop'};Start-Sleep -Milliseconds 3000;$carryRows.Add((& $bodyAt 'dropped'))")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-CarryBody-v1423.ps1').write_bytes(out.encode('utf-8'))
print('ok')
