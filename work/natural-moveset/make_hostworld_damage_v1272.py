"""Derives Test-HostWorldDamage-v1272.ps1 from Test-PairedVictim-v1248l.ps1 (product controller on the Dunwall fixture,
checkpoint restoration) for stage 4 (#14): host-world damage on a combat-bound guard. With the product controller armed
and both peers' combat sessions active, the host runs the lab-only `coop_npc_combat hostworld_test` (1214r) next to the
upper-floor tutorial guard 2: bloodfly damage_periodic, with another streamed NPC as attacker and inflictor, enters the
installed damage observer exactly as a creature's hit does (take 1270e). Pass (runtime): every hit lowers the host's
guard health and the client's replica follows to the same value (HostWorld commit), and the guard stays combat-bound."""
from pathlib import Path
P = Path(__file__).resolve().parent
s = P.joinpath('Test-PairedVictim-v1248l.ps1').read_bytes().decode('utf-8'); nl = '\r\n' if '\r\n' in s else '\n'
lines = s.split(nl)
def idx(prefix, start=0):
    for i in range(start, len(lines)):
        if lines[i].startswith(prefix): return i
    raise AssertionError(prefix)
main = idx('try{')
tail = idx('}catch{$failure=$_.Exception.Message;Save "$out/failure.json"')
head = lines[:main]
head[0] = "param([ValidatePattern('^[a-z0-9-]+$')][string]$Take='hostworld-damage-v1272a',[string]$Candidate='candidate-npc-combat-v1214r',[int]$Hits=3)"
head = [head[0], '# 1272 (stage 4, #14, 1214r): host-world damage on a combat-bound guard. Generated by make_hostworld_damage_v1272.py from 1248l.'] + [l for l in head[1:] if not l.startswith('# ')]
setup = lines[main:idx(' foreach($source in $Sources)')]
setup = [l.replace("operation='PairedVictim1248l'", "operation='HostWorld1272'").replace('sources=$Sources', 'hits=$Hits') for l in setup]
body = r''' $row=[ordered]@{passed=$false;failure=$null;checks=[Collections.Generic.List[string]]::new()}
 try{
  $dirty=$true;Arm
  foreach($q in 'host','client'){C $q 'setviewpos -33 -153 68.1 90 0'}
  $live=WaitLive 'armed' 45000;if(!$live.ok){throw 'Partner presentation not live after arming'}
  $w=[Diagnostics.Stopwatch]::StartNew();do{Start-Sleep -Milliseconds 400;$hc=S host '.npc-combat.json';$cc=S client '.npc-combat.json';$ok=$hc.result-eq'active_native_melee'-and$cc.result-eq'active_native_melee'}while(!$ok-and$w.ElapsedMilliseconds-lt20000)
  if(!$ok){throw "Combat session not active on both peers (host $($hc.result), client $($cc.result))"};$row.checks.Add('Combat session active on both peers')
  $hitRows=[Collections.Generic.List[object]]::new()
  for($i=0;$i-lt$Hits;$i++){
   $g=Guard host;$og=Guard client;$row.guardHost=$g.handle;$row.guardClient=$og.handle
   C host ('setviewpos {0} {1} {2} 0 0' -f (F ([double]$g.position[0]-1.8)),(F ([double]$g.position[1])),(F ([double]$g.position[2]+1.7)));Start-Sleep -Milliseconds 700
   $before=[ordered]@{host=(Q host '--health' $g.handle).current;client=(Q client '--health' $og.handle).current}
   C host 'coop_npc_combat hostworld_test';Start-Sleep -Milliseconds 1800
   $t=S host '.npc-hostworld-test.json';$after=[ordered]@{host=(Q host '--health' $g.handle).current;client=(Q client '--health' $og.handle).current}
   $hc=S host '.npc-combat.json';$cc=S client '.npc-combat.json'
   $hitRows.Add([pscustomobject]@{i=$i;test=$t;before=$before;after=$after;host=($hc|Select-Object result,hostWorldPassed,hostWorldCommitted,committed,lastRetire);client=($cc|Select-Object result,hostWorldApplied,followSubtractions,applied,lastRetire)})
   Save "$out/hits.json" @($hitRows)
   if($t.target-ne$g.handle){throw "Hit $i targeted $($t.target), not the tutorial guard $($g.handle) ($($t.result))"}
   if($t.result-ne'damaged'){throw "Hit ${i}: host-world damage not applied ($($t.result))"}
   if($after.host-ne$after.client){throw "Hit ${i}: guard health differs (host $($after.host), client $($after.client))"}
   $row.checks.Add("Hit ${i}: host $($before.host) -> $($after.host), client $($before.client) -> $($after.client)")
  }
  foreach($q in 'host','client'){foreach($suffix in '.npc-stream.json','.npc-combat.json','.npc-hostworld-test.json'){try{Copy-Item -LiteralPath "$root/work/lab-instances/$q/coop-status.json$suffix" -Destination "$out/$q$suffix" -ErrorAction Stop}catch{}}}
  $hc=S host '.npc-combat.json';$cc=S client '.npc-combat.json'
  $row.counters=[ordered]@{hostWorldPassed=$hc.hostWorldPassed;hostWorldCommitted=$hc.hostWorldCommitted;clientHostWorldApplied=$cc.hostWorldApplied;clientFollowSubtractions=$cc.followSubtractions}
  if($hc.hostWorldCommitted-lt$Hits-or$cc.hostWorldApplied-lt$Hits){throw "HostWorld commits $($hc.hostWorldCommitted), applied $($cc.hostWorldApplied), expected $Hits"}
  $row.checks.Add("$Hits host-world hits shared as HostWorld commits; the client followed each")
  $row.passed=$true
 }catch{$row.failure=$_.Exception.Message}
 try{Restore 'hostworld';$row.restored=$true}catch{$row.restored=$false;$row.failure=(("$($row.failure); restore: "+$_.Exception.Message)).TrimStart('; ')}
 $rows.Add([pscustomobject]$row);Save "$out/hostworld.json" ([pscustomobject]$row)
 if(!$row.restored){throw 'Fixture restore failed'}
 $dirty=$false'''
end = lines[tail:]
end = [l.replace("operation='PairedVictim1248l'", "operation='HostWorld1272'") for l in end]
out = nl.join(head + setup + body.split('\n') + end)
def rep(old, new):
    global out
    assert out.count(old) == 1, old[:70]; out = out.replace(old, new)
rep("scope='paired_victim_alignment: rear choke under the product controller (NPC stream on, natural guard AI), both source roles; partner phases and the observer-world victim recorded; fixture restored after every case.'",
    "scope='Stage 4 host-world damage: under the product controller the host applies lab-only bloodfly damage (another NPC as source) to the combat-bound Dunwall tutorial guard through the installed damage observer; the client replica must follow every hit (HostWorld); fixture restored.'")
rep('"PASS_PAIRED_VICTIM $($rows.Count) cases"', '"PASS_HOSTWORLD_DAMAGE"')
rep('$failure="$($bad.Count) case(s) failed: "+(($bad|ForEach-Object {"$($_.source)-$($_.kind): $($_.failure)"})-join \' | \')', '$failure=($bad|ForEach-Object {$_.failure})-join \' | \'')
P.joinpath('Test-HostWorldDamage-v1272.ps1').write_bytes(out.encode('utf-8'))
print('ok')
