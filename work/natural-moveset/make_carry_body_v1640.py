"""1640 (#117): Test-CarryBody-v1622.ps1 for Shadow Kill on an enemy. With Shadow Kill granted, Emily's and Corvo's
lethal takedowns of the Edge of the World docks photographer left the corpse in both worlds (mission-coverage-v1639a/b):
the native Shadow Kill (ARK_ATTRIBUTE_SHADOWKILL_UNAWARE_NPCS) may cover only enemies, not civilians. Here the victim is
the lab's tutorial guard. -GrantNamed grants named items to the source before the case; after the takedown verdict the
guard's presence and health are recorded in both worlds every 700 ms for 8 s, so a body turned to ash shows as absent.
The take stops after that series (no carry). Generated by make_carry_body_v1640.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1622.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(2, "# 1640 (#117): -GrantNamed and a guard presence series after the takedown, for Shadow Kill on an enemy. Generated by make_carry_body_v1640.py.")
s = '\n'.join(lines)
rep("[switch]$FarReach,[switch]$ReleaseNpcStream)", "[switch]$FarReach,[switch]$ReleaseNpcStream,[string]$GrantNamed='')")
rep("  $capture=$null;$peerCapture=$null;$monitor=$null\n  try{\n",
    "  $capture=$null;$peerCapture=$null;$monitor=$null\n  try{\n"
    "   if($GrantNamed){$row.granted=@();foreach($gnItem in @($GrantNamed-split','|Where-Object {$_})){C $source \"coop_grant_named $gnItem\";Start-Sleep -Milliseconds 900\n"
    "     $row.granted+=[pscustomobject]@{item=$gnItem;result=$(try{(S $source '.observer-camera.json').itemGrant.named.result}catch{$null})}}}\n")
rep("   $carryRows=[Collections.Generic.List[object]]::new();$carrying=$false\n",
    "   $gpSeries=[Collections.Generic.List[object]]::new();$gpW=[Diagnostics.Stopwatch]::StartNew()\n"
    "   while($gpW.ElapsedMilliseconds-lt8000){$gpRow=[ordered]@{ms=$gpW.ElapsedMilliseconds}\n"
    "    foreach($gpR in 'host','client'){$gpN=@($(try{(Q $gpR '--world-npcs').npcs}catch{@()})|Where-Object {$_.spawnerName-eq'ld_spawner_guard_tutorial_2'})\n"
    "     $gpRow[$gpR]=$(if($gpN.Count){$gpH=try{Q $gpR '--health' $gpN[0].handle}catch{$null};[ordered]@{present=$true;position=$gpN[0].position;current=$gpH.current;hidden=$gpH.explicitHidden}}else{[ordered]@{present=$false}})}\n"
    "    $gpSeries.Add([pscustomobject]$gpRow);Start-Sleep -Milliseconds 700}\n"
    "   Save \"$out/$key-guard-presence.json\" @($gpSeries)\n"
    "   $gpEnd=$gpSeries[$gpSeries.Count-1];$row.guardEnd=[ordered]@{host=$gpEnd.host;client=$gpEnd.client}\n"
    "   $row.checks.Add(\"Guard after the takedown: host present $($gpEnd.host.present) hidden $($gpEnd.host.hidden), client present $($gpEnd.client.present) hidden $($gpEnd.client.hidden)\")\n"
    "   $row.passed=$true;throw 'presence-done'\n"
    "   $carryRows=[Collections.Generic.List[object]]::new();$carrying=$false\n")
rep("  }catch{$row.failure=$_.Exception.Message}\n", "  }catch{if($_.Exception.Message-ne'presence-done'){$row.failure=$_.Exception.Message}}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-CarryBody-v1640.ps1').write_bytes(out.encode('utf-8'))
print('ok')
