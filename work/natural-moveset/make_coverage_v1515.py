"""1515 (#11, product-mode props): Record-Coverage-v1506.ps1 also saves both roles' grenade, Heart, trap and ranged prop
status at the end of every case (1504b: the grenade, Heart and stun mine cases passed in a product session, but the props
are too small to judge on film and their status was not saved; 1214ej stopped hiding network props outside the lab
isolation). Generated by make_coverage_v1515.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1506.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1515 (#11): end-of-case prop status (grenade, Heart, trap, ranged). Generated by make_coverage_v1515.py.\n" + s[first:]
rep("foreach($suffix in '.movement.json','.shadow-stream.json','.product.json')",
    "foreach($suffix in '.movement.json','.shadow-stream.json','.product.json','.grenade-prop.json','.heart-prop.json','.trap-prop.json','.ranged-prop.json')")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-Coverage-v1515.ps1').write_bytes(out.encode('utf-8'))
print('ok')
