"""1433 (#11 carry_object_place_throw): Probe-ObjectCarry-v1269.ps1 with the native HoldObject state dumped while the bottle
is held. Presenting the object in the partner's hand needs the held movable's identity on the source. The player state
table holds each state object at mode + 0x10 + id * 8 (world identity tests, confirmed static), and d2_runtime_probe
--player-states prints mode. 1.4 s and 2.0 s after the pickup press the case reads the HoldObject49 pointer from that
slot and dumps the state's first 0x400 bytes with each word's RTTI type (--object, read only); the movable's entity
shows up as a typed pointer. Generated by make_object_carry_v1433.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Probe-ObjectCarry-v1269.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1433 (#11): the HoldObject49 state is dumped while the bottle is held. Generated by make_object_carry_v1433.py.\n" + s[first:]
rep("   $samples=[Collections.Generic.List[object]]::new();$watch=[Diagnostics.Stopwatch]::StartNew();$pressed=$false\n",
    "   $samples=[Collections.Generic.List[object]]::new();$watch=[Diagnostics.Stopwatch]::StartNew();$pressed=$false;$holdDumps=[Collections.Generic.List[object]]::new()\n")
rep("    $player=try{Q $source '--player-states'}catch{$null};",
    "    if($case.name-eq'bottle'-and$holdDumps.Count-lt2-and$watch.ElapsedMilliseconds-ge(2600+600*$holdDumps.Count)){\n"
    "     $ps=try{Q $source '--player-states'}catch{$null};$slotAt=$null;$statePtr=$null;$dump=$null\n"
    "     if($ps){$slotAt='0x{0:x}' -f ([Convert]::ToUInt64(($ps.mode-replace'^0x',''),16)+0x10+49*8)\n"
    "      $statePtr=try{(Q $source '--object' $slotAt).words[0].word}catch{$null};if($statePtr){$dump=try{Q $source '--object' $statePtr}catch{$null}}}\n"
    "     $holdDumps.Add([pscustomobject]@{ms=$watch.ElapsedMilliseconds;active=@($ps.active|ForEach-Object {$_.id});slot=$slotAt;state=$statePtr;type=$dump.type;words=$dump.words})}\n"
    "    $player=try{Q $source '--player-states'}catch{$null};")
rep("   Save \"$out/$key-samples.json\" @($samples)\n",
    "   Save \"$out/$key-samples.json\" @($samples);Save \"$out/$key-hold-dumps.json\" @($holdDumps);$row.holdDumps=$holdDumps.Count;$row.holdStateType=@($holdDumps|ForEach-Object {$_.type})\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Probe-ObjectCarry-v1433.ps1').write_bytes(out.encode('utf-8'))
print('ok')
