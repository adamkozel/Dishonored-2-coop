"""1631 (#127): Record-MissionCoverage-v1630.ps1 with a corpse pose series after the takedown. After Emily's lethal
takedown, Corvo's corpse stays out of its ragdoll (physics mode 3, 1631a) and stands; 1214fg's ragdoll request laid it
down but Emily's copy then stood upside down (1632a). For 8 s after the verdict, about every 400 ms, the case records
for each world the target's actor root and render root (--npc-pose: position and axes), its physics mode and pending
value, and its NPC entry (result, poses, roots); the full skeleton (--skeleton) is saved at about 1, 4 and 7 s.
-CorpseRagdoll turns on the host's research toggle (coop_npc_corpse_ragdoll, candidate 1214fi) for the take.
Generated by make_mission_coverage_v1631.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1630.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(1, "# 1631 (#127): a corpse pose series in both worlds after the takedown; -CorpseRagdoll sets the host toggle. Generated by make_mission_coverage_v1631.py.")
s = '\n'.join(lines)
first = s.index('\n')
s = s[:first].rstrip()[:-1] + ',[switch]$CorpseRagdoll)' + s[first:]
# the toggle before the case, off after it
rep("    if($case-eq'takedown'){", "    if($case-eq'takedown'){if($CorpseRagdoll){C host 'coop_npc_corpse_ragdoll on';$row.corpseRagdoll=$true}")
old_later = "     $row.targetPhysics.later=[ordered]@{host=(& $phRead host);client=(& $phRead client)}\n"
series = ("     $psSeries=[Collections.Generic.List[object]]::new();$psW=[Diagnostics.Stopwatch]::StartNew();$psSk=0\n"
          "     while($psW.ElapsedMilliseconds-lt8000){$psRow=[ordered]@{ms=$psW.ElapsedMilliseconds}\n"
          "      foreach($psR in 'host','client'){$psN=@((Q $psR '--world-npcs').npcs|Where-Object spawnerName -eq $TargetSpawner);if(!$psN.Count){$psRow[$psR]=$null;continue}\n"
          "       $psP=try{Q $psR '--npc-pose' $psN[0].handle}catch{$null};$psPh=& $phRead $psR\n"
          "       $psE=@($(try{(S $psR '.npc-stream.json').entries}catch{@()})|Where-Object {('0x{0:x}' -f [uint32]$_.handle)-eq[string]$psN[0].handle})\n"
          "       $psRow[$psR]=[ordered]@{root=$psP.root;render=$psP.render;mode=$psPh.mode;pending=$psPh.pending;result=$(if($psE.Count){$psE[0].result}else{$null});poses=$(if($psE.Count){$psE[0].poses}else{$null});roots=$(if($psE.Count){$psE[0].roots}else{$null})}\n"
          "       if(($psSk-eq0-and$psW.ElapsedMilliseconds-ge1000)-or($psSk-eq1-and$psW.ElapsedMilliseconds-ge4000)-or($psSk-eq2-and$psW.ElapsedMilliseconds-ge7000)){try{Save \"$out/$key-$psR-skeleton-$psSk.json\" (Q $psR '--skeleton' $psN[0].handle)}catch{}}}\n"
          "      if(($psSk-eq0-and$psW.ElapsedMilliseconds-ge1000)-or($psSk-eq1-and$psW.ElapsedMilliseconds-ge4000)-or($psSk-eq2-and$psW.ElapsedMilliseconds-ge7000)){$psSk++}\n"
          "      $psSeries.Add([pscustomobject]$psRow);Start-Sleep -Milliseconds 150}\n"
          "     Save \"$out/$key-corpse-pose.json\" @($psSeries);$row.corpsePoseSamples=$psSeries.Count\n"
          "     try{$row.corpseRagdollStatus=[ordered]@{enabled=(S host '.npc-stream.json').corpseRagdollEnabled;ragdolls=(S host '.npc-stream.json').corpseRagdolls}}catch{}\n"
          "     if($CorpseRagdoll){C host 'coop_npc_corpse_ragdoll off'}\n")
rep(old_later, old_later + series)
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1631.ps1').write_bytes(out.encode('utf-8'))
print('ok')
