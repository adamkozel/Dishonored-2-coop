"""1228m (#11): Test-UseVariants-v1228l.ps1 sampling both peers' shadow-stream status and the source's movement status
(use counters) during each case. Diagnostic for the client-sourced lock and door uses that the host never presents
(takes 1228m/1228n: the client registers the use, the host's useEvent never advances; client taps still pass)."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-UseVariants-v1228l.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string[]]$Only=@('locks','taps','window'))", "[string[]]$Only=@('locks','taps','window'))\n"
    "# 1228m (#11): per-case samples of both peers' shadow-stream status and the source's movement status. Generated by\n# make_use_variants_v1228m.py.")
old = """-WindowStyle Hidden -PassThru;$samplers.Add($srcSampler)
  Start-Sleep -Milliseconds 1000"""
new = """-WindowStyle Hidden -PassThru;$samplers.Add($srcSampler)
  $diag=foreach($d in @(@($src,'.shadow-stream.json','source-shadow'),@($obs,'.shadow-stream.json','observer-shadow'),@($src,'.movement.json','source-movement'))){
   Start-Process (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-File',"$PSScriptRoot/Sample-StatusFile-v1023.ps1",'-Path',"$root/work/lab-instances/$($d[0])/coop-status.json$($d[1])",'-Out',"$out/use-$src-$target-$($d[2]).ndjson",'-DurationMs',10000,'-IntervalMs',50) -WindowStyle Hidden -PassThru}
  foreach($p in $diag){$samplers.Add($p)}
  Start-Sleep -Milliseconds 1000"""
rep(old, new)
rep("if(!$sampler.WaitForExit(15000)){Stop-Process -Id $sampler.Id};", "if(!$sampler.WaitForExit(15000)){Stop-Process -Id $sampler.Id};foreach($p in $diag){if(!$p.WaitForExit(15000)){Stop-Process -Id $p.Id}};")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-UseVariants-v1228m.ps1').write_bytes(out.encode('utf-8'))
print('ok')
