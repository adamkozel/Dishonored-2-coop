"""1228k (#33): Test-UseVariants-v1228j.ps1 for the Dunwall sink tap. The small room put the 1228/1228b observer behind a
wall. -Side (default 1.2) sets the observer's sideways offset, and -TapsOnly runs only the Dunwall sink cases, so a close
over-the-shoulder spot (for example -Back 1.3 -Side 0.5 -ObserverPitch 25) with the camera held at the teleport frames it."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-UseVariants-v1228j.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string[]]$LeverSources=@('host','client'))", "[string[]]$LeverSources=@('host','client'),[double]$Side=1.2,[switch]$TapsOnly)\n"
    "# 1228k (#33): -Side and -TapsOnly (Dunwall sink cases only). Generated by make_use_variants_v1228k.py.")
rep("$ox=[double]$sp[0]-$Back*$ux-1.2*$uy;$oy=[double]$sp[1]-$Back*$uy+1.2*$ux", "$ox=[double]$sp[0]-$Back*$ux-$Side*$uy;$oy=[double]$sp[1]-$Back*$uy+$Side*$ux")
rep("""  UseCase host client $locks 5 'ring_locker|lock'
  UseCase client host $locks 5 'ring_locker|lock'
  UseCase host client @('esc_env_rich_sink_tap_01_1') 4 'tap'
  UseCase client host @('esc_env_rich_sink_tap_01_1') 4 'tap'
  # #5 re-check: the host-source generic use of the window ended at 24% in 1214c.
  UseCase host client @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional
  UseCase client host @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional""",
"""  if(!$TapsOnly){UseCase host client $locks 5 'ring_locker|lock'
  UseCase client host $locks 5 'ring_locker|lock'}
  UseCase host client @('esc_env_rich_sink_tap_01_1') 4 'tap'
  UseCase client host @('esc_env_rich_sink_tap_01_1') 4 'tap'
  # #5 re-check: the host-source generic use of the window ended at 24% in 1214c.
  if(!$TapsOnly){UseCase host client @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional
  UseCase client host @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional}""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-UseVariants-v1228k.ps1').write_bytes(out.encode('utf-8'))
print('ok')
