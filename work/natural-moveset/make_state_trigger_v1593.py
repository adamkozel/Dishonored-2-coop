"""1593 (#102): Probe-StateTrigger-v1590.ps1 with -Partner: every sample also reads the partner's presentation of the
source (the peer's .movement.json heartHeld, heartVariant, heartWeight and its .heart-prop.json kind and active flag),
and the row keeps the held kinds and variants the partner presented at weight above 0.5 and the prop kinds it showed.
For the Timepiece in A Crack in the Slab (candidate 1214eu): the shift's raise (variant 7) and teleport (8) exist only
there. Generated by make_state_trigger_v1593.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Probe-StateTrigger-v1590.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$Midnight,[switch]$KeepWorld)", "[switch]$Midnight,[switch]$KeepWorld,[switch]$Partner)")
first = s.index('\n') + 1
s = s[:first] + "# 1593 (#102): -Partner samples the partner's presentation of the source. Generated by make_state_trigger_v1593.py.\n" + s[first:]
rep("$trace.Add([ordered]@{ms=$w.ElapsedMilliseconds;active=$ids;stance=$ps.stance;logic=(S $Role).localGameLogicState});",
    "$pt=[ordered]@{ms=$w.ElapsedMilliseconds;active=$ids;stance=$ps.stance;logic=(S $Role).localGameLogicState}\n"
    "    if($Partner){$pm=try{S $peer '.movement.json'}catch{$null};$pq=try{Get-Content \"$root/work/lab-instances/$peer/coop-status.json.heart-prop.json\" -Raw|ConvertFrom-Json}catch{$null}\n"
    "     if($pm){$pt.heartHeld=$pm.heartHeld;$pt.heartVariant=$pm.heartVariant;$pt.heartWeight=$pm.heartWeight};if($pq){$pt.propKind=$pq.kind;$pt.propActive=$pq.active}}\n"
    "    $trace.Add($pt);")
rep("closedWithB=$closed;logicAfter=$logic;midnight=$midSum;",
    "closedWithB=$closed;logicAfter=$logic;midnight=$midSum;"
    "partnerHeld=@($trace|Where-Object {[double]$_.heartWeight-gt.5}|ForEach-Object {[int]$_.heartHeld}|Sort-Object -Unique);"
    "partnerVariants=@($trace|Where-Object {[double]$_.heartWeight-gt.5}|ForEach-Object {[int]$_.heartVariant}|Sort-Object -Unique);"
    "partnerProps=@($trace|Where-Object {$_.propActive}|ForEach-Object {[int]$_.propKind}|Sort-Object -Unique);")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Probe-StateTrigger-v1593.ps1').write_bytes(out.encode('utf-8'))
print('ok')
