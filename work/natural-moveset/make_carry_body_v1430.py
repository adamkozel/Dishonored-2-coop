"""1430 (#11 emily_far_reach_pull_variants): Test-CarryBody-v1427.ps1 with a Far Reach aim sweep that dumps the native
grapple sensor. In 1427a the pull upgrades were granted but every cast still travelled: the aim never targeted the body,
and the aim loop scene (Scene_1) is the same for a surface and an object. The player's arkCpntPlayerSensorGrapple
(vtable RVA 0x1b3fdf8, found in the player component list, confirmed runtime) holds the aim result. Before the usual
tries, the source holds the aim for 9 s (asynchronously) and steps the pitch from 8 degrees above to 10 degrees below
the computed body pitch; at each step it saves the sensor object's first 0x400 bytes (d2_runtime_probe --object, read
only) and the grapple beam state. Comparing the steps against the body's handle locates the target field for a later
aim-until-targeted harness. Generated by make_carry_body_v1430.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1427.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("# 1427 (#11):", "# 1430 (#11): a Far Reach aim sweep dumps the native grapple sensor before the tries. Generated by make_carry_body_v1430.py.\n# 1427 (#11):")
rep("     $offsets=@(0,-3,3)\n",
    "     # 1430: aim sweep with grapple sensor dumps (read only).\n"
    "     $sensor=try{@((Q $source '--components' 1).components|Where-Object {$_.type-eq'.?AVarkCpntPlayerSensorGrapple@@'})[0].pointer}catch{$null};$row.sensorPointer=$sensor\n"
    "     $row.bodyHandle=try{(Guard $source).handle}catch{$null};$dumps=[Collections.Generic.List[object]]::new()\n"
    "     if($sensor){$dumps.Add([pscustomobject]@{pitch=$null;phase='rest';words=$(try{(Q $source '--object' $sensor).words}catch{$null});grapple=$(try{Q $source '--player-grapple'}catch{$null})})\n"
    "      $ltp=Start-Process (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-File',\"$lab/Send-D2Input.ps1\",'-Role',$source,'-LeftTrigger','255','-DurationMs','9000') -WindowStyle Hidden -PassThru;Start-Sleep -Milliseconds 800\n"
    "      foreach($dp in -8,-6,-4,-3,-2,-1,0,1,2,3,4,6,8,10){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $source -Pitch ($basePitch+$dp) -Quick|Out-Null}catch{};Start-Sleep -Milliseconds 200\n"
    "       $dumps.Add([pscustomobject]@{pitch=$basePitch+$dp;phase='aim';words=$(try{(Q $source '--object' $sensor).words}catch{$null});grapple=$(try{Q $source '--player-grapple'}catch{$null})})}\n"
    "      try{$ltp.WaitForExit(9000)|Out-Null}catch{};Start-Sleep -Milliseconds 2000\n"
    "      C $source ('setviewpos {0} {1} {2} {3} 0' -f (F $fx2),(F $fy2),(F $eyeZ),$fyaw.ToString('F4',$inv));Start-Sleep -Milliseconds 500\n"
    "      for($t=0;$t-lt2;$t++){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $source -Pitch $basePitch -Quick|Out-Null;break}catch{Start-Sleep -Milliseconds 300}}}\n"
    "     Save \"$out/$key-sensor-sweep.json\" @($dumps);$row.sensorDumps=$dumps.Count\n"
    "     $offsets=@(0,-3,3)\n")
rep("'-t','16'", "'-t','34'")
rep("-ArgumentList @($pids[$source],'--watch-midnight','12000')", "-ArgumentList @($pids[$source],'--watch-midnight','30000')")
rep("if(!$fm.WaitForExit(14000))", "if(!$fm.WaitForExit(32000))")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-CarryBody-v1430.ps1').write_bytes(out.encode('utf-8'))
print('ok')
