"""1384 (#11 counterattack): Record-MissionCoverage-v1376.ps1 with a faster counter. In 1376h/i Emily won two timed parries
but no counter followed: the block was held in synchronous 1.2 s presses, so a parry win was only seen after the hold
ended, and an attack press alone at 7.3 s started no swing; at 18.4 s the aim correction, which carries the block button
while blocking, pressed it again on the staggered guard and Emily choked him (choke_front, the shared button). With
-CounterOnParry the block is now held in 400 ms presses (a short press is also what gives a timed parry), the source's
player scenes are polled right after each one, and a parry win is answered at once with three attack presses 90 ms apart;
for 2.5 s after it nothing presses the block button. Generated by make_mission_coverage_v1384.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1376.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

first = s.split('\n', 1)
assert first[0].startswith('param(')
s = first[0] + "\n# 1384 (#11): -CounterOnParry blocks in 400 ms presses and answers a parry win at once; no block press for 2.5 s after.\n# Generated by make_mission_coverage_v1384.py.\n" + first[1]
rep("$nextBlock=0;$aimAt=-9999;",
    "$nextBlock=0;$counterUntil=0;$aimAt=-9999;\n"
    "     $counterCheck={$md2=try{Q $source '--midnight'}catch{$null};$win=@($md2.instances|Where-Object {$_.asset-like'*gameplay/player/*sword_parry_win*'}).Count;$tc=$watch.ElapsedMilliseconds\n"
    "      if($win-and$tc-ge$counterUntil){foreach($i in 0..2){& \"$lab/Send-D2Input.ps1\" -Role $source -RightTrigger 255 -DurationMs 160|Out-Null;Start-Sleep -Milliseconds 90};$row.counterPresses.Add($tc);$counterUntil=$watch.ElapsedMilliseconds+2500;$nextBlock=$counterUntil}};")
rep("if($phase-eq'block'-and$t-lt$nextBlock-300){& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder",
    "if($phase-eq'block'-and$t-lt$nextBlock-300-and$t-ge$counterUntil){& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder")
rep("if($phase-eq'block'-and$t-ge$nextBlock){& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder -DurationMs 1200|Out-Null;$nextBlock=$t+1500}}",
    "if($phase-eq'block'-and$t-ge$nextBlock-and$t-ge$counterUntil){$bms=if($CounterOnParry){400}else{1200};& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder -DurationMs $bms|Out-Null;$nextBlock=$t+$(if($CounterOnParry){550}else{1500})\n"
    "        if($CounterOnParry){. $counterCheck}}}")
rep("if($parry-and!$lastParry){& \"$lab/Send-D2Input.ps1\" -Role $source -RightTrigger 255 -DurationMs 180|Out-Null;$row.counterPresses.Add($t);$nextBlock=$t+2500}",
    "if($parry-and!$lastParry-and$watch.ElapsedMilliseconds-ge$counterUntil){foreach($i in 0..2){& \"$lab/Send-D2Input.ps1\" -Role $source -RightTrigger 255 -DurationMs 160|Out-Null;Start-Sleep -Milliseconds 90};$row.counterPresses.Add($t);$counterUntil=$watch.ElapsedMilliseconds+2500;$nextBlock=$counterUntil}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1384.ps1').write_bytes(out.encode('utf-8'))
print('ok')
