"""1594 (#113): Probe-StateTrigger-v1593.ps1 with -NpcAll: once the map has loaded (and any -At/-Grant has run), both
roles' --npc-authority-all (probe-only candidate 1214ev: every unique world NPC with health, AI flags, pause references,
scheduler and tree, and the acquire, host-stream and paused rules) is saved before the triggers as
npc-authority-all-<role>.json, and again after them as npc-authority-all-<role>-after.json. For the scripted civilians
the client never binds (the Edge of the World photographer, the Royal Conservatory servant) and the overseer at his
market post. Generated by make_state_trigger_v1594.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Probe-StateTrigger-v1593.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$KeepWorld,[switch]$Partner)", "[switch]$KeepWorld,[switch]$Partner,[switch]$NpcAll)")
first = s.index('\n') + 1
s = s[:first] + "# 1594 (#113): -NpcAll saves both roles' --npc-authority-all before and after the triggers. Generated by make_state_trigger_v1594.py.\n" + s[first:]
anchor = " foreach($spec in @($Triggers-split';'|Where-Object {$_})){$name,$ms=$spec-split':';$ms=[int]$ms\n"
rep(anchor,
    " if($NpcAll){foreach($r in 'host','client'){Save \"$out/npc-authority-all-$r.json\" (Q $r '--npc-authority-all')}}\n" + anchor)
rep(" Save \"$out/rows.json\" @($rows);",
    " Save \"$out/rows.json\" @($rows);if($NpcAll){foreach($r in 'host','client'){Save \"$out/npc-authority-all-$r-after.json\" (Q $r '--npc-authority-all')}};")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Probe-StateTrigger-v1594.ps1').write_bytes(out.encode('utf-8'))
print('ok')
