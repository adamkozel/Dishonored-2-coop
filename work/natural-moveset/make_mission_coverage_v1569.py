"""1569 (#11 wall_and_window_variants): Record-MissionCoverage-v1567.ps1 with -ClientPrebind: before the PlaceAt fixture
places the target, the client stands its own copy of it where it already is (coop_lab_npc_place at the copy's own
position and heading, read from --world-npcs) and waits up to 8 s for that copy to bind as a ready NPC-stream channel,
so its AI is leased (paused) before the host moves the target; the host then places it alone and the stream carries
the new root to the replica. Corvo's window takedowns: without a client placement the client's scripted copy never bound
(1548b, 1557b, 1564c-f; #113), and with the client's copy placed at the window (-PlaceBoth, 1566a-c) the host's overseer
was attacking from the start (sword drawn; the client's copy, its AI still running beside Corvo's presented body, is the
likely trigger through the NPC attack relay, hypothesis). The row keeps prebind {ms, bound, result, position}.
Generated by make_mission_coverage_v1569.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1567.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$ChokeProbe)", "[switch]$ChokeProbe,[switch]$ClientPrebind)")
first = s.index('\n') + 1
s = s[:first] + "# 1569 (#11): -ClientPrebind binds the client's copy of the target before the host places it. Generated by make_mission_coverage_v1569.py.\n" + s[first:]
anchor = "      $npcYaw=if([double]::IsNaN($TargetYaw)){$pa[3]}else{$TargetYaw};$row.targetYaw=$npcYaw\n"
rep(anchor, anchor +
    "      if($ClientPrebind){$cq=@(Living client|Where-Object {$_.spawnerName-eq$TargetSpawner-and$_.unique});$row.prebind=[ordered]@{ms=$null;bound=$false;result=$null;position=$null}\n"
    "       if($cq.Count){$cp=$cq[0].position;$co=$cq[0].orientation;$cyaw=[Math]::Atan2([double]$co[1],[double]$co[0])*180/[Math]::PI;$row.prebind.position=$cp\n"
    "        C client ('coop_lab_npc_place {0} {1} {2} {3} {4}' -f $TargetSpawner,([double]$cp[0]).ToString('F3',$inv),([double]$cp[1]).ToString('F3',$inv),([double]$cp[2]).ToString('F3',$inv),$cyaw.ToString('F2',$inv))\n"
    "        $ch=[Convert]::ToUInt64(([string]$cq[0].handle-replace'^0x',''),16);$bw=[Diagnostics.Stopwatch]::StartNew();$ce=@()\n"
    "        do{Start-Sleep -Milliseconds 250;$ns=try{S client '.npc-stream.json'}catch{$null};$ce=@($ns.entries|Where-Object {[uint64]$_.handle-eq$ch-and$_.ready})}while(!$ce.Count-and$bw.ElapsedMilliseconds-lt8000)\n"
    "        $row.prebind.ms=$bw.ElapsedMilliseconds;$row.prebind.bound=[bool]$ce.Count;$row.prebind.result=$(if($ce.Count){$ce[0].result}else{$null})}}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1569.ps1').write_bytes(out.encode('utf-8'))
print('ok')
