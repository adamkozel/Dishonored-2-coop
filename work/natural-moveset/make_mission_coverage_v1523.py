"""1523 (#11 wall_and_window_variants, enemy_body_size_variants): Record-MissionCoverage-v1522.ps1 with fixes for the
1519-1522 fixtures:
- -WindowStand (with -PlaceAt): the source keeps the stand worked out from the window (PlaceAt minus Behind along its
  yaw) instead of being stood again behind the target from the target's own heading (1519a: the overseer had turned
  north, so Corvo was moved outside the window), the observer camera is held inside the room behind the source, and a
  client source also places the target in its own world (1510b, 1519b: the client's world never showed it moved).
- -ApproachYaw DEG: the approach direction (stand, re-stand and camera) is turned DEG degrees around the target
  (-90: the source comes from the target's left and the camera looks from in front). 1521a/b: the stand point behind
  the sleeping overseer's armchair was on a barrel, so the source stood on it, above his head.
- -PrePitch DEG: the source's pitch is set once, right after it is stood (setviewpos keeps pitch), so no pitch step
  delays a timed press (1522a/b: the look-down after the knockdown took 2.8 s, and the overseer was up again).
- -KnockCrouch (with -KnockdownSettle): the source crouches right after it is stood beside the knocked-down body,
  bringing its view down to the body.
Generated by make_mission_coverage_v1523.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1522.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$BlastFromBehind,[switch]$KnockdownSettle)",
    "[switch]$BlastFromBehind,[switch]$KnockdownSettle,[switch]$WindowStand,[double]$ApproachYaw=0,[double]$PrePitch=-999,[switch]$KnockCrouch)")
first = s.index('\n') + 1
s = s[:first] + "# 1523 (#11): -WindowStand, -ApproachYaw, -PrePitch, -KnockCrouch. Generated by make_mission_coverage_v1523.py.\n" + s[first:]
# Window targets are placed in the client's own world too when the client is the source.
place = "C host ('coop_lab_npc_place {0} {1} {2} {3} {4}' -f $TargetSpawner,$pa[0].ToString('F3',$inv),$pa[1].ToString('F3',$inv),$pa[2].ToString('F3',$inv),$pa[3].ToString('F2',$inv))"
rep(place, "foreach($pr in @('host')+@(if($WindowStand-and$source-eq'client'){'client'})){C $pr ('coop_lab_npc_place {0} {1} {2} {3} {4}' -f $TargetSpawner,$pa[0].ToString('F3',$inv),$pa[1].ToString('F3',$inv),$pa[2].ToString('F3',$inv),$pa[3].ToString('F2',$inv))}", 3)
# Approach direction turned around the target.
rot = "if($ApproachYaw){$ar=$ApproachYaw*[Math]::PI/180;$rx=$fx*[Math]::Cos($ar)-$fy*[Math]::Sin($ar);$ry=$fx*[Math]::Sin($ar)+$fy*[Math]::Cos($ar);$fx=$rx;$fy=$ry;$row.approachYaw=$ApproachYaw}\n"
rep("     $sx=[double]$np[0]-$Behind*$fx;$sy=[double]$np[1]-$Behind*$fy;$sz=[double]$np[2];$syaw=[Math]::Atan2($fy,$fx)*180/[Math]::PI\n     $mx=",
    "     " + rot + "     $sx=[double]$np[0]-$Behind*$fx;$sy=[double]$np[1]-$Behind*$fy;$sz=[double]$np[2];$syaw=[Math]::Atan2($fy,$fx)*180/[Math]::PI\n     $mx=")
rep("$gl=[Math]::Max(.1,[Math]::Sqrt($gx*$gx+$gy*$gy));$gx/=$gl;$gy/=$gl\n",
    "$gl=[Math]::Max(.1,[Math]::Sqrt($gx*$gx+$gy*$gy));$gx/=$gl;$gy/=$gl\n"
    "        if($ApproachYaw){$ar=$ApproachYaw*[Math]::PI/180;$rx=$gx*[Math]::Cos($ar)-$gy*[Math]::Sin($ar);$ry=$gx*[Math]::Sin($ar)+$gy*[Math]::Cos($ar);$gx=$rx;$gy=$ry}\n")
# Window stand: no re-stand from the target's heading; the camera inside the room behind the source's left shoulder.
rep("     if(!$Perch){C $source (P $sx $sy ($sz+1.7) $syaw);Start-Sleep -Milliseconds 700};$row.sourceStart=(Q $source '--player').candidatePosition",
    "     if(!$Perch-and!$WindowStand){C $source (P $sx $sy ($sz+1.7) $syaw);Start-Sleep -Milliseconds 700};$row.sourceStart=(Q $source '--player').candidatePosition\n"
    "     if($PrePitch-gt-90){try{& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $source -Pitch $PrePitch -Quick|Out-Null;$row.prePitch=$PrePitch}catch{$row.prePitch=\"failed: $($_.Exception.Message)\"}}")
cam = "     C $peer ('coop_observer_camera hold_at {0} {1} {2}' -f $hcx.ToString('F3',$inv),$hcy.ToString('F3',$inv),$hcz.ToString('F3',$inv));Start-Sleep -Milliseconds 400;$row.camera=@($hcx,$hcy,$hcz)\n"
rep(cam, "     if($WindowStand-and$PlaceAt){$hcx=$row.approach[0]-1.5*$wfx-1.2*$wfy;$hcy=$row.approach[1]-1.5*$wfy+1.2*$wfx;$hcz=$pa[2]+1.75}\n" + cam)
rep("if(!$replaced-and$t-ge(450+$delay)-and!$Perch-and!$KnockdownSettle){",
    "if(!$replaced-and$t-ge(450+$delay)-and!$Perch-and!$KnockdownSettle-and!$WindowStand){")
# Crouch beside the knocked-down body before the press.
rep(";$row.knockedAt=$qp;$row.knockFlight=[Math]::Round($moved,2)\n",
    ";$row.knockedAt=$qp;$row.knockFlight=[Math]::Round($moved,2)\n"
    "         if($KnockCrouch){I $source B 150;$row.knockCrouch=$watch.ElapsedMilliseconds}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1523.ps1').write_bytes(out.encode('utf-8'))
print('ok')
