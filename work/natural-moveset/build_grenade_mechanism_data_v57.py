"""Pin the native six-joint cosmetic grenade tracks; never copy events."""
import json, math, hashlib
from pathlib import Path
from edge_data import poses

P = Path(__file__).resolve().parent
S = P.parents[1] / 'outputs/d2-coop-lab/src'
read = lambda p: json.loads(p.read_text(encoding='utf-8-sig'))
manifest = read(P / 'grenade-mechanism-manifest-v55.json')
rig = read(P / 'item-mechanisms/grenade-skeleton.json')['joints']
assert len(rig) == 6
lines = ['#pragma once', '// Generated by build_grenade_mechanism_data_v57.py; native pose samples only.',
         'struct GrenadeMechanismClip {unsigned joints,frames;const float (*qts)[7];};']
fmt = lambda v: ','.join(f'{float(x):.9f}f' for x in v)
lines.append('inline constexpr short grenadeMechanismParents[]={' + ','.join(str(j['parent']) for j in rig) + '};')
lines.append('inline constexpr float grenadeMechanismBind[][7]={' + ','.join('{' + fmt(j['bindLocalQTS'][:7]) + '}' for j in rig) + '};')
reports = []
for part in ('idle', 'cooking_in', 'cooking_idle'):
    m = next(r for r in manifest if r['id'] == 'grenade_' + part)
    track = poses(P / m['sample_file'])
    assert track['sha256'] == m['sample_sha256'] and track['joints'] == 6
    frames = track['frames']
    for frame in frames:
        for q in frame:
            assert all(math.isfinite(v) for v in q)
            assert abs(sum(v*v for v in q[:4]) - 1) < .001
            assert all(abs(q[k]-1) < 1e-6 for k in range(8,11))
    name = 'grenadeMechanism_' + part
    lines.append(f'inline constexpr float {name}_poses[][7]={{' + ','.join('{' + fmt(q[:7]) + '}' for frame in frames for q in frame) + '};')
    lines.append(f'inline constexpr GrenadeMechanismClip {name}={{6,{len(frames)},{name}_poses}};')
    reports.append(dict(phase=part, asset=m['asset'], asset_sha256=m['asset_sha256'], sample=m['sample_file'], sample_sha256=m['sample_sha256'], frames=len(frames), joints=6, events=False))
lines.append('inline GrenadeMechanismClip grenadeMechanismClip(unsigned variant){return variant==3?grenadeMechanism_cooking_in:(variant>=4?grenadeMechanism_cooking_idle:grenadeMechanism_idle);}')
header = S / 'grenade_mechanism_data.h'
header.write_text('\n'.join(lines) + '\n')
(P / 'grenade-mechanism-runtime-sources-v57.json').write_text(json.dumps(dict(executable='B671F8249422862BF557D00AAB2F4BB671ED4515CC10AD8A8A9DECAD84516180', header=str(header.relative_to(P.parents[1])), header_sha256=hashlib.sha256(header.read_bytes()).hexdigest(), clips=reports, events=False, runtime_verified=False), indent=2))
print('Generated three pinned native six-joint grenade tracks; runtime application pending')
