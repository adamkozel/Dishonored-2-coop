    "    $ps=try{Q $source '--player-states'}catch{$null};$ss=try{S $source '.shadow-stream.json'}catch{$null};$os=try{S $peer '.shadow-stream.json'}catch{$null};$om=try{S $peer '.movement.json'}catch{$null}\n"
    "    [pscustomobject]@{tag=$tag;source=$sv;observer=$ov;gap=$gap;active=@($ps.active|ForEach-Object {$_.id})\n"
