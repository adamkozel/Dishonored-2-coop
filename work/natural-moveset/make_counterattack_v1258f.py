"""1258f (#9, 1214ai): Test-Counterattack-v1258e.ps1 with a side camera for visual review. Take 1258l filmed Emily's counter
from 3.5 m behind the guard, about 7 m from the fight in an 800x540 window, too far to judge. The observer now stands
beside the fight's midpoint (guard + 1.25 m along its facing) at 3.0, then 2.4, then 3.6 m on either side, looking at the
midpoint with a 12 degree pitch; the old behind-the-guard spots remain the fallback."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258e.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258l',[string]$Candidate='candidate-npc-combat-v1214ah'",
    "[string]$Take='counterattack-v1258m',[string]$Candidate='candidate-npc-combat-v1214ai'")
rep("# 1258e (#9): the counter cycle",
    "# 1258f (#9, 1214ai): side camera at the fight's midpoint (3.0/2.4/3.6 m either side, pitch 12) for visual review; 1258l filmed\n"
    "# from 3.5 m behind the guard, about 7 m from the fight. Generated by make_counterattack_v1258f.py.\n"
    "# 1258e (#9): the counter cycle")
rep("""   $picked=$null;$camTrials=[Collections.Generic.List[object]]::new()
   foreach($back in 3.5,2.9,4.1){$tx=[double]$g.position[0]-$back*$fx;$ty=[double]$g.position[1]-$back*$fy
    C $peer ('setviewpos {0} {1} 68.1 {2} 0' -f (F $tx),(F $ty),$look.ToString('F4',$inv));Start-Sleep -Milliseconds 650;$feet=(Q $peer '--player-states').position
    $ok=[math]::Abs($feet[2]-$g.position[2])-lt.3-and[math]::Abs($feet[0]-$tx)-lt.4-and[math]::Abs($feet[1]-$ty)-lt.4
    $camTrials.Add([pscustomobject]@{back=$back;x=$tx;y=$ty;feet=$feet;ok=$ok});if($ok){$picked=$back;$ax=$tx;$ay=$ty;break}}
   Save "$out/$key-camera-trials.json" @($camTrials);$row.filmed=$null-ne$picked
   if($row.filmed){& "$PSScriptRoot/Set-ObserverPitch.ps1" -Role $peer -Pitch 22 -Quick|Out-Null
   C $peer ('setviewpos {0} {1} 69.1 {2} 0' -f (F $ax),(F $ay),$look.ToString('F4',$inv));Start-Sleep -Milliseconds 120""",
"""   $picked=$null;$camTrials=[Collections.Generic.List[object]]::new();$pitch=22
   $mx=[double]$g.position[0]+1.25*$fx;$my=[double]$g.position[1]+1.25*$fy
   $spots=[Collections.Generic.List[object]]::new()
   foreach($d in 3.0,2.4,3.6){foreach($side in 1,-1){$tx=$mx-$side*$d*$fy;$ty=$my+$side*$d*$fx;$spots.Add(@{kind="side$side";d=$d;x=$tx;y=$ty;look=[Math]::Atan2($my-$ty,$mx-$tx)*180/[Math]::PI;pitch=12})}}
   foreach($back in 3.5,2.9,4.1){$spots.Add(@{kind='back';d=$back;x=[double]$g.position[0]-$back*$fx;y=[double]$g.position[1]-$back*$fy;look=$look;pitch=22})}
   foreach($sp in $spots){$tx=$sp.x;$ty=$sp.y
    C $peer ('setviewpos {0} {1} 68.1 {2} 0' -f (F $tx),(F $ty),([double]$sp.look).ToString('F4',$inv));Start-Sleep -Milliseconds 650;$feet=(Q $peer '--player-states').position
    $ok=[math]::Abs($feet[2]-$g.position[2])-lt.3-and[math]::Abs($feet[0]-$tx)-lt.4-and[math]::Abs($feet[1]-$ty)-lt.4
    $camTrials.Add([pscustomobject]@{kind=$sp.kind;d=$sp.d;x=$tx;y=$ty;look=$sp.look;feet=$feet;ok=$ok});if($ok){$picked=$sp.kind;$ax=$tx;$ay=$ty;$look=[double]$sp.look;$pitch=$sp.pitch;break}}
   Save "$out/$key-camera-trials.json" @($camTrials);$row.filmed=$null-ne$picked;$row.camera=$picked
   if($row.filmed){& "$PSScriptRoot/Set-ObserverPitch.ps1" -Role $peer -Pitch $pitch -Quick|Out-Null
   C $peer ('setviewpos {0} {1} 69.1 {2} 0' -f (F $ax),(F $ay),$look.ToString('F4',$inv));Start-Sleep -Milliseconds 120""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258f.ps1').write_bytes(out.encode('utf-8'))
print('ok')
