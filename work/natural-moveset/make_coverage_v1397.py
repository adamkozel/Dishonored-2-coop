N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1390.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

LAB = ['labknock', 'labstunfront', 'labstunback', 'labstunleft', 'labstunright']
labq = ",".join(f"'{c}'" for c in LAB)
rep("# 1390 (#11):", "# 1397 (#11): lab hit probes (coop_lab_hit, 1214dl, lab only). Generated by make_coverage_v1397.py.\n# 1390 (#11):")
