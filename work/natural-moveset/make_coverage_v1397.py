rep("     nomana3=@(",
    "".join(f"     {c}=@(@(600,'hold','on'),@(1500,'watchmid',9000),@(2500,'selfcmd','coop_lab_hit {a}'),@(10000,'hold','off'));\n" for c, a in plans.items())
    + "     nomana3=@(")
rep(";'peercmd'{C $peer $d[2]};", ";'peercmd'{C $peer $d[2]};'selfcmd'{C $source $d[2]};")
rep("     if($case-in'nomana2','nomana3'){$manaTrace.Add(",
    "     if($case-like'lab*'){$kps=try{Q $source '--player-states'}catch{$null};$manaTrace.Add([pscustomobject]@{ms=$t;active=@($kps.active|ForEach-Object {'{0}@{1}' -f $_.id,$_.vtable})})}\n"
    "     if($case-in'nomana2','nomana3'){$manaTrace.Add(")
