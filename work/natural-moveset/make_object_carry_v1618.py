"""1618 (#115): Probe-ObjectCarry-v1616.ps1 whose movers check resolves a "gone" entity across the whole world. The check
compares the entities in a 6 m box around the target before and after the case, so an object pulled out of the box
or taken counted as "gone". In object-carry-v1617a the pulled tumbler was "gone" in Emily's world although her held
tracker had seen it at rest 10 s after the pull. A gone mover is now looked up by name in the full entity list:
change "elsewhere" with its position, or "absent" when it no longer exists. Generated by make_object_carry_v1618.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Probe-ObjectCarry-v1616.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1618 (#115): a gone mover is looked up in the whole world. Generated by make_object_carry_v1618.py.\n" + s[first:]
rep("      if(!$a.Count){$m+=[pscustomobject]@{name=$e.name;handle=$e.handle;change='gone'}}",
    "      if(!$a.Count){$all=@(try{(Q $q '--entities').entities|Where-Object name -eq $e.name}catch{@()})\n"
    "       $m+=$(if($all.Count){[pscustomobject]@{name=$e.name;handle=$e.handle;change='elsewhere';to=$all[0].position}}else{[pscustomobject]@{name=$e.name;handle=$e.handle;change='absent'}})}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Probe-ObjectCarry-v1618.ps1').write_bytes(out.encode('utf-8'))
print('ok')
