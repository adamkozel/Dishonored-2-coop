"""1622 (#115): Test-CarryBody-v1621.ps1 with a control for the refused body pull. In carry-body-v1621a Emily's Far Reach
never targeted the unconscious body: arkCpntPowerGrapple +0xdc stayed 0x3fff0010 (no entity) through both tries while her
copy of the body was a host-presented replica (NPC entry client_unconscious, host poses arriving). With -ReleaseNpcStream
the source turns off the product maintenance and its NPC stream before the tries (the channels stop and their holds are
released), so the body is a native unconscious body in her world; the tries then show whether the power targets it. The
source re-enables both after the tries. Generated by make_carry_body_v1622.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1621.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(2, "# 1622 (#115): -ReleaseNpcStream turns the source's NPC stream off before the pull tries. Generated by make_carry_body_v1622.py.")
s = '\n'.join(lines)
rep("[int]$KillAttempts=15,[switch]$FarReach)", "[int]$KillAttempts=15,[switch]$FarReach,[switch]$ReleaseNpcStream)")
rep("     $offsets=@(0,-3,3)\n",
    "     $offsets=@(0,-3,3)\n"
    "     if($ReleaseNpcStream){C $source 'coop_product_auto off';C $source 'coop_npc_stream off';Start-Sleep -Milliseconds 2500;$row.releasedNpcEntry=& $bodyEntry\n"
    "      $row.releasedBody=try{(Guard $source).position}catch{$null};$row.releasedHealth=try{Q $source '--health' $row.bodyHandle}catch{$null}}\n")
rep("     $row.farReachCarry=$carrying;",
    "     if($ReleaseNpcStream){C $source 'coop_npc_stream on';C $source 'coop_product_auto on';Start-Sleep -Milliseconds 1500}\n"
    "     $row.farReachCarry=$carrying;")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-CarryBody-v1622.ps1').write_bytes(out.encode('utf-8'))
print('ok')
