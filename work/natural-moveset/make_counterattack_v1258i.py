"""1258i (#9, 1214aj): Test-Counterattack-v1258h.ps1 with a block-hit trigger. The counter finishers in takes 1258l
(fatality_leftleg_medium_a) and 1258m (fatality_rightarm_fast_a) both followed a BLOCKED guard hit (sword_parry_hit_1/2)
by 0.44-0.73 s, not sword_parry_win. The cycle now holds block (400 ms packets renewed every 250 ms, up to 3 s) while polling
the source's scene log every 20 ms, and attacks as soon as a blocked hit or a parry win is live."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258h.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258p'", "[string]$Take='counterattack-v1258q'")
rep("# 1258h (#9, 1214aj): reactive counter",
    "# 1258i (#9, 1214aj): hold block up to 3 s and attack as soon as a blocked hit (sword_parry_hit_1/2) or parry win is live\n"
    "# (1258l/1258m: the finishers followed blocked hits). Generated by make_counterattack_v1258i.py.\n"
    "# 1258h (#9, 1214aj): reactive counter")
rep("function ParryWin($path){try{$t=Get-Content -LiteralPath $path -Tail 1 -ErrorAction Stop;$t-match'combat/sword_parry_win\\.midnightscene'}catch{$false}}",
    "function ParryWin($path){try{$t=Get-Content -LiteralPath $path -Tail 1 -ErrorAction Stop;$t-match'combat/sword_parry_(win|hit_1|hit_2)\\.midnightscene'}catch{$false}}")
rep("""     $won=$false;for($tap=0;$tap-lt4-and!$won;$tap++){& "$lab/Send-D2Input.ps1" -Role $source -Button RightShoulder -DurationMs 350|Out-Null
      if(ParryWin "$out/$key-scenes.ndjson"){$won=$true;$row.parryWins=1+[int]$row.parryWins}else{Start-Sleep -Milliseconds 120}}""",
"""     $won=$false;$bw=[Diagnostics.Stopwatch]::StartNew()
     while(!$won-and$bw.ElapsedMilliseconds-lt3000){& "$lab/Send-D2Input.ps1" -Role $source -Button RightShoulder -DurationMs 400|Out-Null;$until=$bw.ElapsedMilliseconds+250
      while($bw.ElapsedMilliseconds-lt$until){if(ParryWin "$out/$key-scenes.ndjson"){$won=$true;$row.parryWins=1+[int]$row.parryWins;break};Start-Sleep -Milliseconds 20}}""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258i.ps1').write_bytes(out.encode('utf-8'))
print('ok')
