"""1277i (#11, carry_body_lift_idle_move_drop_throw): Test-CarryBody-v1277h.ps1 with its own recording of the carry. In
carry-body-v1277h the camera moved beside the carry path, but the case's captures had already ended (the harness waits for
them right after the takedown, before the pickup), so the lift, the carry walk and the drop were never recorded. A second
capture of the observer window (and the source window) now starts after the camera move and runs 18 s, covering the walk,
the drop and the settle. Generated by make_carry_body_v1277i.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1277h.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

rep("# 1277h (#11):", "# 1277i (#11): a second capture records the carry itself. Generated by make_carry_body_v1277i.py.\n# 1277h (#11):")
rep("""    C $peer ('coop_observer_camera hold_at {0} {1} {2}' -f (F $cx),(F $cy),(F $cz));Start-Sleep -Milliseconds 400;$row.carryCameraHeld=(S $peer '.observer-camera.json').active}catch{$row.carryCameraError=$_.Exception.Message}
""", """    C $peer ('coop_observer_camera hold_at {0} {1} {2}' -f (F $cx),(F $cy),(F $cz));Start-Sleep -Milliseconds 400;$row.carryCameraHeld=(S $peer '.observer-camera.json').active}catch{$row.carryCameraError=$_.Exception.Message}
   # 1277i: record the carry (the case captures ended after the takedown).
   $carryCaptures=@();foreach($pair in @(@($source,'source'),@($peer,'observer'))){$hwnd=(Get-Process -Id $pids[$pair[0]]).MainWindowHandle.ToInt64()
    $carryCaptures+=Start-Process (Get-Command ffmpeg).Source -ArgumentList @('-hide_banner','-loglevel','warning','-nostdin','-f','lavfi','-i',"gfxcapture=hwnd=${hwnd}:capture_cursor=0:max_framerate=30:width=-2:height=-2,hwdownload,format=bgra",'-t','18','-an','-c:v','libx264','-preset','veryfast','-crf','18','-pix_fmt','yuv420p','-fps_mode','passthrough','-movflags','+faststart',"$out/$key-carry-$($pair[1]).mp4") -WindowStyle Hidden -RedirectStandardError "$out/$key-carry-$($pair[1])-capture.log" -RedirectStandardOutput "$out/$key-carry-$($pair[1])-capture.stdout" -PassThru}
""")
rep("""   I $source X 900;Start-Sleep -Milliseconds 3000;$carryRows.Add((& $bodyAt 'dropped'));Start-Sleep -Milliseconds 2000;$end=& $bodyAt 'settled';$carryRows.Add($end)
""", """   I $source X 900;Start-Sleep -Milliseconds 3000;$carryRows.Add((& $bodyAt 'dropped'));Start-Sleep -Milliseconds 2000;$end=& $bodyAt 'settled';$carryRows.Add($end)
   foreach($c in $carryCaptures){try{if(!$c.WaitForExit(20000)){Stop-Process -Id $c.Id}}catch{}};$row.carryRecorded=@($carryCaptures).Count
""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-CarryBody-v1277i.ps1').write_bytes(out.encode('utf-8'))
print('ok')
