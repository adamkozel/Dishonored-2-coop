"""1258q (#9/#11 parry views, 1214ap): Test-Counterattack-v1258m.ps1 (attack, hold block until a blocked hit, attack again -
the cycle that kept the guard engaged in 1258y) with the free observer camera and the lab health hold. 1258y framed the fight
off the right edge because the observer's body had to stand at the camera spot. The camera is now held with hold_at
-CamDistance metres beside the fight's midpoint (guard + 1.25 m along its facing; the spot may hang in open air), 2.2 m above
the guard's feet, looking at the midpoint with a 20 degree pitch, chosen on -CamSide. -HealthHold keeps the source alive
(coop_player_health_hold, its first runtime check: the status records refills)."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258m.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258z',[string]$Candidate='candidate-npc-combat-v1214aj'",
    "[string]$Take='counterattack-v1258ap',[string]$Candidate='candidate-npc-combat-v1214ap',[switch]$HealthHold,[double]$CamSide=1,[double]$CamDistance=3.0")
rep("# 1258m (#9, 1214aj): 30 degree pitch",
    "# 1258q (#9/#11, 1214ap): free observer camera beside the fight (hold_at) and -HealthHold. Generated by\n# make_counterattack_v1258q.py.\n# 1258m (#9, 1214aj): 30 degree pitch")
start = s.index("   $picked=$null;$camTrials=[Collections.Generic.List[object]]::new();$pitch=22")
end = s.index("   C $peer 'coop_observer_camera hold';Start-Sleep -Milliseconds 300;Save \"$out/$key-observer-camera.json\" (S $peer '.observer-camera.json')}")
end = s.index('\n', end) + 1
s = s[:start] + """   $mx=[double]$g.position[0]+1.25*$fx;$my=[double]$g.position[1]+1.25*$fy;$ax=$mx-$CamSide*$CamDistance*$fy;$ay=$my+$CamSide*$CamDistance*$fx;$az=[double]$g.position[2]+2.2
   $look=[Math]::Atan2($my-$ay,$mx-$ax)*180/[Math]::PI
   C $peer ('setviewpos -33 -153 68.1 {0} 0' -f $look.ToString('F4',$inv));Start-Sleep -Milliseconds 400
   & "$PSScriptRoot/Set-ObserverPitch.ps1" -Role $peer -Pitch 20 -Quick|Out-Null
   C $peer ('coop_observer_camera hold_at {0} {1} {2}' -f (F $ax),(F $ay),$az.ToString('F3',$inv));Start-Sleep -Milliseconds 400
   $cam=S $peer '.observer-camera.json';Save "$out/$key-observer-camera.json" $cam;$row.filmed=[bool]$cam.active;$row.camera=@($ax,$ay,$az)
""" + s[end:]
rep("   $dirty=$true;Arm\n", "   $dirty=$true;Arm\n   if($HealthHold){C $source 'coop_player_health_hold on';$row.healthHold=$true};$row.sourceHealthStart=try{(Q $source '--health' 1).current}catch{$null}\n")
rep("  try{Restore $key;$row.restored=$true}",
    "  $row.sourceHealthEnd=try{(Q $source '--health' 1).current}catch{$null};if($HealthHold){try{$row.healthHoldStatus=(S $source '.observer-camera.json').healthHold;C $source 'coop_player_health_hold off'}catch{}}\n  try{Restore $key;$row.restored=$true}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258q.ps1').write_bytes(out.encode('utf-8'))
print('ok')
