"""1605 (#118): Record-MissionCoverage-v1600.ps1 with -NoLoad. The cases run in the current mission, inside a
Route-Mission -HoldAtEnd hold, without loading a map and without restoring the Dunwall fixture (Restore-RouteHold-v1303
restores afterwards). For takedown victims that mission scripts only wake later: the Addermire Institute's orphan
guards and wolfhounds stay unstarted at map start (state-trigger-v1602a, 1603a). Generated by make_mission_coverage_v1605.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1600.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
i = s.index('param(')
j = s.index(')\n', i)
s = s[:j] + ',[switch]$NoLoad' + s[j:]
first = s.index('\n') + 1
s = s[:first] + "# 1605 (#118): -NoLoad runs the cases in the current mission hold. Generated by make_mission_coverage_v1605.py.\n" + s[first:]
rep(' C host "campaign $MapInfo $Chaos corvo";C client "campaign $MapInfo $Chaos emily"\n'
    ' $g=WaitGameplay 300000;Save "$out/load-log.json" $g.log;if(!$g.ready){throw \'Both instances did not reach the same mission gameplay\'}\n',
    ' if(!$NoLoad){C host "campaign $MapInfo $Chaos corvo";C client "campaign $MapInfo $Chaos emily"\n'
    '  $g=WaitGameplay 300000;Save "$out/load-log.json" $g.log;if(!$g.ready){throw \'Both instances did not reach the same mission gameplay\'}}\n')
rep('  if($dirty){\n   $cw=[Diagnostics.Stopwatch]::StartNew()\n',
    '  if($dirty-and!$NoLoad){\n   $cw=[Diagnostics.Stopwatch]::StartNew()\n')
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1605.ps1').write_bytes(out.encode('utf-8'))
print('ok')
