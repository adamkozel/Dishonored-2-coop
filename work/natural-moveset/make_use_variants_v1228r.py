"""1228r (#11 door_open_close_locked): Test-UseVariants-v1228p.ps1 with -DoorName and -SecondUse. The door case used the
office door ld_door_350cm_int_rich_wood_01, which is locked (chapter 47: "Royal Quarters Key needed"; 1228zf/zg filmed
the partner reaching for it). The adjacent unlocked door ld_door_350cm_int_rich_wood_01_3 opens and closes with two
ordinary taps (641/642). -DoorName picks the door; -SecondUse taps use again 1.8 s after the first registered use (the
close) and records whether the native use count rose again. Generated by make_use_variants_v1228r.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-UseVariants-v1228p.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

i = s.index('\n') + 1
s = s[:i] + "# 1228r (#11): -DoorName picks the door (the _3 door is unlocked); -SecondUse taps again to close it.\n# Generated by make_use_variants_v1228r.py.\n" + s[i:]
rep("[double]$EyeHeight=1.65)", "[double]$EyeHeight=1.65,[string]$DoorName='ld_door_350cm_int_rich_wood_01',[switch]$SecondUse)")
assert s.count("@('ld_door_350cm_int_rich_wood_01')") >= 1
s = s.replace("@('ld_door_350cm_int_rich_wood_01')", "@($DoorName)")
rep("  Save \"$out/press-$src-$target.json\" @($pressLog)\n",
    "  if($SecondUse-and$used){Start-Sleep -Milliseconds 1800;$before2=(S $src '.movement.json').sourceUses;$f=F $src\n"
    "   I $src X 400;Start-Sleep -Milliseconds 450;I $src;Start-Sleep -Milliseconds 1200;$uses2=(S $src '.movement.json').sourceUses\n"
    "   $row.secondUse=$uses2-gt$before2;$pressLog.Add(@{attempt='second';focusedAtPress=$f.focused;name=$f.name;sourceUsesAfter=$uses2;used=$row.secondUse})}\n"
    "  Save \"$out/press-$src-$target.json\" @($pressLog)\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-UseVariants-v1228r.ps1').write_bytes(out.encode('utf-8'))
print('ok', s.count('$DoorName'))
