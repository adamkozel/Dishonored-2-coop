"""1625 (#115): Record-MissionCoverage-v1624.ps1 that saves both worlds' NPC combat, NPC stream and shadow stream status
right after the Far Reach body pull (as $key-<role>-<name>-farreach.json). In mission-coverage-v1623a the host's copy of
the pulled body flew with Emily's although the host applied no streamed root or reverse pose during the pull; the
hypothesis is the shared combat damage relay (grapple damage declarations). In 1624a Corvo's choke left the photographer
in the water, so no spot could aim at her (the spots stood Emily in the sea); the host case needs an inland target.
The spot search also skips a body more than 1.5 m below the caster's start, which marks a body in the water.
Generated by make_mission_coverage_v1625.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1624.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(1, "# 1625 (#115): -FarReachBody saves both worlds' combat and stream status after the pull. Generated by make_mission_coverage_v1625.py.")
s = '\n'.join(lines)
rep("      Save \"$out/$key-farreach-pull.json\" @($fbPull);",
    "      foreach($fbR in 'host','client'){foreach($fbName in 'npc-combat','npc-stream','shadow-stream'){try{Save \"$out/$key-$fbR-$fbName-farreach.json\" (S $fbR \".$fbName.json\")}catch{}}}\n"
    "      Save \"$out/$key-farreach-pull.json\" @($fbPull);")
rep("      $row.farReach=[ordered]@{body=$fbB.position;",
    "      if($fbZ-lt$sz-1.5){$row.checks.Add(\"Far Reach body: the body lies $([Math]::Round($sz-$fbZ,2)) m below the approach (in the water); no pull\");throw 'Far Reach body: the body is in the water'}\n"
    "      $row.farReach=[ordered]@{body=$fbB.position;")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1625.ps1').write_bytes(out.encode('utf-8'))
print('ok')
