"""1514 (#118, #11 enemy_body_size_variants): Record-MissionCoverage-v1509.ps1 with -ProbeTarget: once the target is chosen,
the target's AI components (decision, reflex, attack), its health and the host's NPC authority catalog are read with the
runtime probe in both worlds and saved, to find why gravehounds are never bound in NPC authority (1508b: the hound by
Emily was not among the 24 bound channels on either side). A refused read is saved as its error. Generated by
make_mission_coverage_v1514.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1509.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$PreWindblast,[switch]$PreBendTime)", "[switch]$PreWindblast,[switch]$PreBendTime,[switch]$ProbeTarget)")
first = s.index('\n') + 1
s = s[:first] + "# 1514 (#118): -ProbeTarget saves the target's AI, health and the NPC authority catalog. Generated by make_mission_coverage_v1514.py.\n" + s[first:]
anchor = "$row.target=[ordered]@{spawner=$TargetSpawner;definition=$tg[0].definition;position=$np;forward=@($fx,$fy)};$row.kind=$TakedownKind\n"
rep(anchor, anchor +
    "     if($ProbeTarget){$th=[Convert]::ToUInt64(([string]$tg[0].handle-replace'^0x',''),16);$row.targetHandle=$th\n"
    "      foreach($r in 'host','client'){foreach($m in '--ai-decision','--ai-reflex','--ai-attack','--health'){$f=\"$out/$key-probe-$r$($m-replace'^--','-').json\"\n"
    "        $raw=& \"$lab/bin/d2_runtime_probe.exe\" $pids[$r] $m $th 2>&1;\"exit=$LASTEXITCODE\"|Set-Content \"$f.exit\";$raw|Set-Content $f}\n"
    "       $raw=& \"$lab/bin/d2_runtime_probe.exe\" $pids[$r] '--npc-authority' 2>&1;$raw|Set-Content \"$out/$key-probe-$r-npc-authority.json\"}}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1514.ps1').write_bytes(out.encode('utf-8'))
print('ok')
