"""1228j (#33): Test-UseVariants-v1228i.ps1 with observer distance, pitch and lever sources as parameters. In 1228i Emily's
lever use (filmed by Corvo) was fully framed, but Corvo's (filmed by Emily from 2.4 m behind, pitch 15) lost his head and
shoulders above the frame. -Back (default 2.4), -ObserverPitch (default 15) and -LeverSources (default both) set them."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-UseVariants-v1228i.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$LeversOnly)", "[switch]$LeversOnly,[double]$Back=2.4,[double]$ObserverPitch=15,[string[]]$LeverSources=@('host','client'))\n"
    "# 1228j (#33): -Back, -ObserverPitch and -LeverSources (1228i cut Corvo's head off at 2.4 m and pitch 15). Generated by\n"
    "# make_use_variants_v1228j.py.")
rep("$ox=[double]$sp[0]-2.4*$ux-1.2*$uy;$oy=[double]$sp[1]-2.4*$uy+1.2*$ux", "$ox=[double]$sp[0]-$Back*$ux-1.2*$uy;$oy=[double]$sp[1]-$Back*$uy+1.2*$ux")
rep("$row.observerPitch=Pitch $obs 15;", "$row.observerPitch=Pitch $obs $ObserverPitch;")
rep("foreach($leverSource in 'host','client'){", "foreach($leverSource in $LeverSources){")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-UseVariants-v1228j.ps1').write_bytes(out.encode('utf-8'))
print('ok')
