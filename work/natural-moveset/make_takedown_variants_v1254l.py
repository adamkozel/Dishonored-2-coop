"""1254l (#11, paired actions): Test-TakedownVariants-v1254h.ps1 with a stance-aware crouch. Every placement tapped B to
crouch, but B toggles the native crouch: a source still crouched from the previous case stood up in the guard's view.
Emily's front takedowns failed in 1254h and 1254j ("guard moved or noticed the source") while Corvo's passed. The source
now presses B only when its native stance is not crouched (stance 1), and records the stance before the takedown.
Generated by make_takedown_variants_v1254l.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-TakedownVariants-v1254h.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

rep("# 1254h (#11):", "# 1254l (#11): crouch only when not crouched (B toggles). Generated by make_takedown_variants_v1254l.py.\n# 1254h (#11):")
rep("I $source B 150;Start-Sleep -Milliseconds 500;",
    "$st0=try{[int](Q $source '--player-states').stance}catch{-1};if($st0-ne1){I $source B 150;Start-Sleep -Milliseconds 500};$row.stanceBefore=@($st0,$(try{[int](Q $source '--player-states').stance}catch{-1}));")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-TakedownVariants-v1254l.ps1').write_bytes(out.encode('utf-8'))
print('ok')
