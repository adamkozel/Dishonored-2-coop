"""1199f (#11 map_load_checkpoint_recovery, diagnostic): Test-LifecycleRecovery-v1199e.ps1 that also saves each peer's
entities named like the partner clone (d2coop, corvo, emily) after the load and after the restart. Take 1199e showed a
detached pair of shoulders and arms beside Corvo on the client after the shared restart only. Hypothesis: the checkpoint
save captured the previous partner clone and the restart partially restored it next to the fresh clone."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-LifecycleRecovery-v1199e.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='mission-lifecycle-v1199e',", "[string]$Take='mission-lifecycle-v1199f',")
rep("# 1199e: -FreeCam", "# 1199f: saves partner-like entities per peer after load and restart (detached arms after restart in 1199e).\n# Generated by make_lifecycle_v1199f.py.\n# 1199e: -FreeCam")
rep(""" foreach($r in 'host','client'){Save "$out/player-$tag-$r.json" (Q $r '--player')}
 if($FreeCam){""", """ foreach($r in 'host','client'){Save "$out/player-$tag-$r.json" (Q $r '--player')}
 foreach($r in 'host','client'){try{$ents=@((Q $r '--entities').entities|Where-Object {$_.name-match'(?i)d2coop|corvo|emily|arm_'});Save "$out/entities-$tag-$r.json" @($ents)}catch{Save "$out/entities-$tag-$r.json" @{error=$_.Exception.Message}}}
 if($FreeCam){""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-LifecycleRecovery-v1199f.ps1').write_bytes(out.encode('utf-8'))
print('ok')
