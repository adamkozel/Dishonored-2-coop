"""1258h (#9, 1214aj): Test-Counterattack-v1258g.ps1 with a reactive counter cycle. Holding block 1.6 s and then attacking
blindly produced two parry wins in takes 1258i-1258o (a held block mostly gives plain blocks, and in 1258n the attack after
the win recoiled). The cycle now taps block (350 ms down, 120 ms up, up to four taps) so a fresh block press meets more
guard swings, and attacks as soon as the source's scene log shows sword_parry_win."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258g.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258n'", "[string]$Take='counterattack-v1258p'")
rep("# 1258g (#9, 1214aj): walkway camera spots",
    "# 1258h (#9, 1214aj): reactive counter - tap block (350/120 ms, up to 4 taps) and attack as soon as sword_parry_win is live.\n"
    "# Generated by make_counterattack_v1258h.py.\n"
    "# 1258g (#9, 1214aj): walkway camera spots")
rep("function SceneLive($path){",
    "function ParryWin($path){try{$t=Get-Content -LiteralPath $path -Tail 1 -ErrorAction Stop;$t-match'combat/sword_parry_win\\.midnightscene'}catch{$false}}\n"
    "function SceneLive($path){")
rep("""    if($kind-eq'counter'){if(!$row.counterStarted){$row.counterStarted=$true;Start-Sleep -Milliseconds 2000};& "$lab/Send-D2Input.ps1" -Role $source -Button RightShoulder -DurationMs $BlockMs|Out-Null;Start-Sleep -Milliseconds $BlockMs;& "$lab/Send-D2Input.ps1" -Role $source -RightTrigger 255 -DurationMs 150|Out-Null;Start-Sleep -Milliseconds 150;& "$lab/Send-D2Input.ps1" -Role $source -DurationMs 100|Out-Null}""",
"""    if($kind-eq'counter'){if(!$row.counterStarted){$row.counterStarted=$true;Start-Sleep -Milliseconds 2000}
     $won=$false;for($tap=0;$tap-lt4-and!$won;$tap++){& "$lab/Send-D2Input.ps1" -Role $source -Button RightShoulder -DurationMs 350|Out-Null
      if(ParryWin "$out/$key-scenes.ndjson"){$won=$true;$row.parryWins=1+[int]$row.parryWins}else{Start-Sleep -Milliseconds 120}}
     & "$lab/Send-D2Input.ps1" -Role $source -RightTrigger 255 -DurationMs 150|Out-Null;Start-Sleep -Milliseconds 150;& "$lab/Send-D2Input.ps1" -Role $source -DurationMs 100|Out-Null}""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258h.ps1').write_bytes(out.encode('utf-8'))
print('ok')
