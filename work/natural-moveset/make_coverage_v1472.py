"""1472 (#11 power_upgrade_variants): Record-Coverage-v1469.ps1 with Doppelganger Transposition's swap on the use button.
1456b (a 700 ms hold) and 1462a (a 150 ms tap) both cast a new shade instead of swapping: the native prompt
"Swap with Doppelganger" shows the blue round button (X, the use button), so the swap is X pressed while looking at the
shade. Generated by make_coverage_v1472.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1469.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1472 (#11): the Transposition swap on X. Generated by make_coverage_v1472.py.\n" + s[first:]
rep("@(3200,'lt',700),@(6500,'lt',150));", "@(3200,'lt',700),@(6500,'x',200));")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-Coverage-v1472.ps1').write_bytes(out.encode('utf-8'))
print('ok')
