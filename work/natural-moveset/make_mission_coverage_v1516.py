"""1516 (#11 enemy_body_size_variants, seated): Record-MissionCoverage-v1514.ps1 with -WaitScene REGEX: once the target is
chosen, the host's running scenes are scanned (1.5 s watches, up to 90 s) until one whose asset matches REGEX binds the
target, and only then is the source stood behind him (1512a/b: the office guard was not seated at the press and both
roles ran a plain choke_back). Generated by make_mission_coverage_v1516.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1514.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$PreBendTime,[switch]$ProbeTarget)", "[switch]$PreBendTime,[switch]$ProbeTarget,[string]$WaitScene='')")
first = s.index('\n') + 1
s = s[:first] + "# 1516 (#11): -WaitScene waits until the target is bound to a matching scene. Generated by make_mission_coverage_v1516.py.\n" + s[first:]
anchor = "$row.target=[ordered]@{spawner=$TargetSpawner;definition=$tg[0].definition;position=$np;forward=@($fx,$fy)};$row.kind=$TakedownKind\n"
rep(anchor, anchor +
    "     if($WaitScene){$wh=[Convert]::ToUInt64(([string]$tg[0].handle-replace'^0x',''),16);$ws=[Diagnostics.Stopwatch]::StartNew();$row.waitScene=$null\n"
    "      do{$sw=\"$out/$key-wait-scan.ndjson\";$sp=Start-Process \"$lab/bin/d2_runtime_probe.exe\" -ArgumentList @([string]$pids.host,'--watch-midnight','1500') -WindowStyle Hidden -RedirectStandardOutput $sw -RedirectStandardError \"$out/$key-wait-scan.err\" -PassThru;[void]$sp.WaitForExit(8000)\n"
    "       foreach($ln in @(Get-Content $sw -ErrorAction SilentlyContinue)){$o=$null;try{$o=$ln|ConvertFrom-Json}catch{};if(!$o){continue}\n"
    "        foreach($in in @($o.instances)){if($in.asset-and$in.asset-match$WaitScene-and@($in.bindingsResearch|Where-Object {$_.handle-and[uint64]$_.handle-eq$wh}).Count){$row.waitScene=$in.asset}}}\n"
    "      }while(!$row.waitScene-and$ws.ElapsedMilliseconds-lt90000);$row.waitSceneMs=$ws.ElapsedMilliseconds\n"
    "      if(!$row.waitScene){throw \"The target never entered a scene matching $WaitScene\"}\n"
    "      $tg=@(Living $source|Where-Object {$_.spawnerName-eq$TargetSpawner-and$_.unique});$np=$tg[0].position;$o=$tg[0].orientation;$fx=[double]$o[0];$fy=[double]$o[1];$fl=[Math]::Max(.1,[Math]::Sqrt($fx*$fx+$fy*$fy));$fx/=$fl;$fy/=$fl\n"
    "      $sx=[double]$np[0]-$Behind*$fx;$sy=[double]$np[1]-$Behind*$fy;$sz=[double]$np[2];$syaw=[Math]::Atan2($fy,$fx)*180/[Math]::PI}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1516.ps1').write_bytes(out.encode('utf-8'))
print('ok')
