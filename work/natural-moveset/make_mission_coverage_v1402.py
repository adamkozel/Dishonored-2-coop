"""1402 (#11 shop_dialogue_gestures): Record-MissionCoverage-v1399.ps1 with the shop's raw native reads. In 1399a the partner
vanished for the whole shop (from the press to the menu's close) and reappeared at the counter: every --player and
--player-states read of the source failed while the native shop ran (the shop walk to the counter, the paired
shopkeeper_interact scene with the player bound, the menu), so the source stopped streaming. Every third sample now also
keeps the probe's raw --logic and --player-stance output and, when the states read failed, the raw text (stdout and
stderr) of the --player and --player-states reads, so the shop's logic value, stance and the reader's refusal are named for
a reader that keeps the partner standing at the counter. Generated by make_mission_coverage_v1402.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1399.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

first = s.index('\n') + 1
s = s[:first] + "# 1402 (#11): the shop probe keeps the raw native logic, stance and refused player reads. Generated by make_mission_coverage_v1402.py.\n" + s[first:]
rep("function Q($r,$mode,$arg=0){",
    "function RawQ($r,$mode){$o=& \"$lab/bin/d2_runtime_probe.exe\" $pids[$r] $mode 2>&1|Out-String;[pscustomobject]@{exit=$LASTEXITCODE;text=$(if($o.Length-gt600){$o.Substring(0,600)}else{$o})}}\n"
    "function Q($r,$mode,$arg=0){")
rep("      $ps=try{Q $source '--player-states'}catch{$null};$states.Add([pscustomobject]@{ms=$t;logic=",
    "      $raw=($states.Count%3-eq0);$ps=try{Q $source '--player-states'}catch{$null};$states.Add([pscustomobject]@{ms=$t;"
    "rawLogic=$(if($raw){RawQ $source '--logic'}else{$null});rawStance=$(if($raw){RawQ $source '--player-stance'}else{$null});"
    "rawPlayer=$(if($raw-and!$ps){RawQ $source '--player'}else{$null});rawStates=$(if($raw-and!$ps){RawQ $source '--player-states'}else{$null});logic=")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1402.ps1').write_bytes(out.encode('utf-8'))
print('ok')
