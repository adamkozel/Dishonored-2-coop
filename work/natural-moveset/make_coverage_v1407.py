from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1403.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

first = s.index('\n') + 1
s = s[:first] + "# 1407 (#11): front and back lab blasts face the camera from 4.5 m. Generated by make_coverage_v1407.py.\n" + s[first:]
rep("    C $source 'setviewpos -35 -153 68.1 0 0';Start-Sleep -Milliseconds 400\n    $cx=-35.0;$cy=-153.0+2.8;$cz=66.4+1.5;$cyaw=-90.0\n",
    "    C $source $(if($case-in'labblastfront','labblastback'){'setviewpos -35 -153 68.1 90 0'}else{'setviewpos -35 -153 68.1 0 0'});Start-Sleep -Milliseconds 400\n"
    "    $cx=-35.0;$cy=-153.0+2.8;$cz=66.4+1.5;$cyaw=-90.0\n"
    "    if($case-in'labblastfront','labblastback'){$cy=-153.0+4.5}\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-Coverage-v1407.ps1').write_bytes(out.encode('utf-8'))
print('ok')
