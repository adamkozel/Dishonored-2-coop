"""1376 (#11): Record-MissionCoverage-v1371.ps1 with -WatchScenes. In 1371c (1214dc) Corvo went from Block44 into Choke41 in
the guard fight and the source refused it for 8 packets (stage 2), so the partner dropped out; the take records no scene name.
With -WatchScenes the fight also runs the probe's native scene watcher (--watch-midnight: every scene instance, its
subscene, clock and bindings) on the source back to back in 30 s windows, saving $key-scenes-<n>.ndjson. Generated by
make_mission_coverage_v1376.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1371.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

i = s.index('\n') + 1
s = s[:i] + "# 1376 (#11): -WatchScenes runs the native scene watcher on the source through the guard fight.\n# Generated by make_mission_coverage_v1376.py.\n" + s[i:]
rep("[string]$WatchProbe='',", "[string]$WatchProbe='',[switch]$WatchScenes,")
rep("     $wp=$null;$wn=0\n", "     $wp=$null;$wn=0;$sp=$null;$sn=0\n")
rep("      if($WatchProbe-and(!$wp-or$wp.HasExited)){",
    "      if($WatchScenes-and(!$sp-or$sp.HasExited)){$sn++;$sp=Start-Process \"$lab/bin/d2_runtime_probe.exe\" -ArgumentList @([string]$pids[$source],'--watch-midnight','30000') -WindowStyle Hidden -RedirectStandardOutput \"$out/$key-scenes-$sn.ndjson\" -RedirectStandardError \"$out/$key-scenes-$sn.stderr\" -PassThru}\n"
    "      if($WatchProbe-and(!$wp-or$wp.HasExited)){")
rep("     if($wp-and!$wp.HasExited){[void]$wp.WaitForExit(21000)};$row.combatSceneWindows=$wn\n",
    "     if($wp-and!$wp.HasExited){[void]$wp.WaitForExit(21000)};$row.combatSceneWindows=$wn\n"
    "     if($sp-and!$sp.HasExited){[void]$sp.WaitForExit(31000)};$row.sceneWindows=$sn\n")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1376.ps1').write_bytes(out.encode('utf-8'))
print('ok')
