"""1556 (#11): Record-MissionCoverage-v1554.ps1 with the takedown press written directly. Send-D2Input.ps1 only publishes an
input packet with an expiry (tooling/Publish-D2Packet.ps1) and returns at once, so the harness calls it in its own process
instead of starting a new PowerShell for it, which took about 0.4-0.6 s: the window chokes lost the takedown when the
press landed after the target had walked out of the window (1540a/b, 1548a, 1552a-c), and the knocked-down settles
pressed late. $acted becomes a marker object.
Generated by make_mission_coverage_v1556.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1554.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1556 (#11): takedown presses written directly. Generated by make_mission_coverage_v1556.py.\n" + s[first:]
rep("         $acted=Start-Process (Get-Process -Id $PID).Path -ArgumentList (@('-NoProfile','-File',\"$lab/Send-D2Input.ps1\",'-Role',$source)+$(if($TakedownKind-eq'choke'){@('-Button','RightShoulder','-DurationMs','6500')}else{@('-RightTrigger','255','-DurationMs','200')})) -WindowStyle Hidden -PassThru;$row.actedAt=$watch.ElapsedMilliseconds}}}",
    "         if($TakedownKind-eq'choke'){& \"$lab/Send-D2Input.ps1\" -Role $source -Button RightShoulder -DurationMs 6500|Out-Null}else{& \"$lab/Send-D2Input.ps1\" -Role $source -RightTrigger 255 -DurationMs 200|Out-Null};$acted=[pscustomobject]@{direct=$true};$row.actedAt=$watch.ElapsedMilliseconds}}}")
rep("       $acted=Start-Process (Get-Process -Id $PID).Path -ArgumentList (@('-NoProfile','-File',\"$lab/Send-D2Input.ps1\",'-Role',$source)+$inputArgs) -WindowStyle Hidden -PassThru;$row.actedAt=$t}",
    "       $ia=@{Role=$source};for($ii=0;$ii-lt$inputArgs.Count;$ii+=2){$ia[$inputArgs[$ii].TrimStart('-')]=$(if($inputArgs[$ii]-eq'-Button'){$inputArgs[$ii+1]}else{[int]$inputArgs[$ii+1]})};& \"$lab/Send-D2Input.ps1\" @ia|Out-Null;$acted=[pscustomobject]@{direct=$true};$row.actedAt=$t}")
rep("     if($acted){try{$acted.WaitForExit(8000)|Out-Null}catch{}};",
    "     if($acted-is[Diagnostics.Process]){try{$acted.WaitForExit(8000)|Out-Null}catch{}};")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1556.ps1').write_bytes(out.encode('utf-8'))
print('ok')
