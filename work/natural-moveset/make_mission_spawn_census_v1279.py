"""Derives Test-MissionSpawnCensus-v1279.ps1 from Test-MissionMultiCombat-v1270d.ps1 (Edge of the World under the product
controller, modal clearing, Dunwall fixture restoration) for stage 4 (#14): are NPC spawns synchronized? Both worlds' NPC
catalogs (--world-npcs) are recorded; the host then visits the mission's script_trigger volumes one by one (teleport in,
then back to its spawn spot; trigger mirroring replays each enter/exit for the client's player), and both catalogs are
recorded again. Pass (runtime): the unique NPCs that appeared or disappeared are the same in both worlds (by spawner and
definition). A player death (Game Over) makes the census inconclusive."""
from pathlib import Path
P = Path(__file__).resolve().parent
s = P.joinpath('Test-MissionMultiCombat-v1270d.ps1').read_bytes().decode('utf-8'); nl = '\r\n' if '\r\n' in s else '\n'
lines = s.split(nl)
def idx(prefix):
    for i, l in enumerate(lines):
        if l.startswith(prefix): return i
    raise AssertionError(prefix)
fs, fe = idx('function Fight{'), idx('function WaitGameplay(')
census = r'''function NpcSet($r){@((Q $r '--world-npcs').npcs|Where-Object {$_.unique}|ForEach-Object {"$($_.spawnerName)|$($_.definition)"})|Sort-Object -Unique}
function Census{
 $origin=(Q host '--player').candidatePosition;$ents=@((Q host '--entities').entities)
 $triggers=@($ents|Where-Object {"$($_.name)"-like'script_trigger*'-and$_.position}|Sort-Object name|Select-Object -First $MaxTriggers)
 Save "$out/triggers.json" @($triggers|ForEach-Object {@{name=$_.name;position=$_.position}})
 $before=@{host=@(NpcSet host);client=@(NpcSet client)};Save "$out/npcs-before.json" $before
 $visits=[Collections.Generic.List[object]]::new();$dead=$false
 foreach($t in $triggers){
  C host ('setviewpos {0:F3} {1:F3} {2:F3} 0 0' -f [double]$t.position[0],[double]$t.position[1],([double]$t.position[2]+1.0));Start-Sleep -Milliseconds 700
  C host ('setviewpos {0:F3} {1:F3} {2:F3} 0 0' -f [double]$origin[0],[double]$origin[1],([double]$origin[2]+1.7));Start-Sleep -Milliseconds 400
  ClearModals "trigger-$($t.name)";$lh=(S host).localGameLogicState;$lc=(S client).localGameLogicState
  $visits.Add([pscustomobject]@{name=$t.name;hostLogic=$lh;clientLogic=$lc});if($lh-eq13-or$lc-eq13){$dead=$true;break}}
 Save "$out/visits.json" @($visits)
 Start-Sleep -Milliseconds 6000;ClearModals 'settle'
 $after=@{host=@(NpcSet host);client=@(NpcSet client)};Save "$out/npcs-after.json" $after
 foreach($q in 'host','client'){foreach($suffix in '.npc-stream.json','.product.json'){try{Copy-Item -LiteralPath "$root/work/lab-instances/$q/coop-status.json$suffix" -Destination "$out/census-$q$suffix" -ErrorAction Stop}catch{}}
  try{Copy-Item -LiteralPath "$root/work/lab-instances/$q/coop-status.json.trigger-mirror.json" -Destination "$out/census-$q.trigger-mirror.json" -ErrorAction Stop}catch{}}
 $diff={param($a,$b)@($a|Where-Object {$_-notin$b})}
 $row=[ordered]@{triggers=$triggers.Count;visited=$visits.Count;passed=$false;failure=$null;checks=[Collections.Generic.List[string]]::new()}
 $row.hostAdded=@(& $diff $after.host $before.host);$row.hostRemoved=@(& $diff $before.host $after.host)
 $row.clientAdded=@(& $diff $after.client $before.client);$row.clientRemoved=@(& $diff $before.client $after.client)
 $row.onlyHost=@(& $diff $after.host $after.client);$row.onlyClient=@(& $diff $after.client $after.host)
 $row.onlyHostBefore=@(& $diff $before.host $before.client);$row.onlyClientBefore=@(& $diff $before.client $before.host)
 if($dead){$row.failure='A player died (Game Over) during the trigger walk; the census is inconclusive'}
 elseif(Compare-Object @($row.hostAdded) @($row.clientAdded)){$row.failure="Spawned NPCs differ: host +$($row.hostAdded.Count) client +$($row.clientAdded.Count) ("+(($row.hostAdded|Where-Object {$_-notin$row.clientAdded}|Select-Object -First 5)-join ', ')+")"}
 elseif(Compare-Object @($row.hostRemoved) @($row.clientRemoved)){$row.failure="Despawned NPCs differ: host -$($row.hostRemoved.Count) client -$($row.clientRemoved.Count)"}
 else{$row.passed=$true;$row.checks.Add("$($visits.Count) triggers visited; NPCs added $($row.hostAdded.Count) and removed $($row.hostRemoved.Count), identically in both worlds")}
 $rows.Add([pscustomobject]$row)
}'''
body = lines[:fs] + census.split('\n') + lines[fe:]
s = nl.join(body)
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:80]); s = s.replace(old, new)
rep("[string]$Take='mission-multicombat-v1270d',[string]$Candidate='candidate-npc-combat-v1214m',[string]$Guard='script_spawner_streets_windmill_guard_01',",
    "[string]$Take='mission-spawn-census-v1279a',[string]$Candidate='candidate-npc-combat-v1214af',[int]$MaxTriggers=40,[string]$Guard='unused',")
rep("# 1270 (stage 4, #14): sustained multi-enemy fight on Edge of the World, both players at once. Generated by make_mission_multicombat_v1270.py",
    "# 1279 (stage 4, #14): NPC spawn census across mirrored trigger volumes on Edge of the World. Generated by make_mission_spawn_census_v1279.py from 1270d;" + nl + "# 1270 (stage 4, #14): sustained multi-enemy fight on Edge of the World, both players at once. Generated by make_mission_multicombat_v1270.py")
rep(" Fight" + nl, " Census" + nl)
rep("Save \"$out/identity.json\" @{candidate=$Candidate;dll=$pin.dll;guard=$Guard;fightMs=$FightMs}", "Save \"$out/identity.json\" @{candidate=$Candidate;dll=$pin.dll;maxTriggers=$MaxTriggers}")
i = s.index("scope='Stage 4 sustained multi-enemy fight on Edge of the World"); j = s.index("'", i + 7)
s = s[:i] + "scope='Stage 4 spawn census: on Edge of the World under the product controller the host visits the script trigger volumes (mirrored for the client); the unique NPCs added and removed must match in both worlds; Dunwall fixture restored." + s[j:]
P.joinpath('Test-MissionSpawnCensus-v1279.ps1').write_bytes(s.encode('utf-8'))
print('ok')
