"""1629 (#115): Record-MissionCoverage-v1628.ps1 whose Far Reach spots sweep the aim around the body. In
mission-coverage-v1629a the corpse lay where 1628a's had, but at every spot the reticle rested on the deck beside it (the
power offered a traversal), because the spot aims at the body's entity origin, not at its ragdoll. A lab input packet is
the whole pad state and the newest packet wins, so a separate pitch helper during the trigger hold released the trigger
(that is also why the 1430 and 1621 aim sweeps never entered UsePower). The trigger is now held by re-publishing the pad
state in-process every sample, and right-stick pulses (about 2 degrees each) walk the reticle through thirteen offsets
around the body; the walk stops on the first sample whose aimed handle is the body, and the release then casts the
pull. A spot that never aims at the body releases at the end of its walk (the cast travels). The spot row records the
offset reached. Generated by make_mission_coverage_v1629.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1628.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(1, "# 1629 (#115): the Far Reach spots walk the held aim around the body with in-process pad packets. Generated by make_mission_coverage_v1629.py.")
s = '\n'.join(lines)
old_hold = ("       $fbLt=Start-Process (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-File',\"$lab/Send-D2Input.ps1\",'-Role',$fbCaster,'-LeftTrigger','255','-DurationMs','1400') -WindowStyle Hidden -PassThru\n"
            "       $fbSeen=@();$fbW=[Diagnostics.Stopwatch]::StartNew();while($fbW.ElapsedMilliseconds-lt1350){$fbA=& $fbAim;if($fbA-and$fbA.aim){$fbSeen+=$fbA.aim};Start-Sleep -Milliseconds 40}\n"
            "       $fbHit=@($fbSeen|Where-Object {$_-eq$fbHandle}).Count\n")
new_hold = ("       $fbIn={param($fbRx,$fbRy,$fbMs)& \"$lab/Send-D2Input.ps1\" -Role $fbCaster -LeftTrigger 255 -RightX $fbRx -RightY $fbRy -DurationMs $fbMs|Out-Null}\n"
            "       & $fbIn 0 0 900;Start-Sleep -Milliseconds 500;$fbSeen=@();$fbHit=0;$fbCur=@(0,0)\n"
            "       foreach($fbT in @(@(0,0),@(0,1),@(0,-1),@(-1,0),@(1,0),@(0,2),@(0,-2),@(-2,0),@(2,0),@(-1,1),@(1,1),@(-1,-1),@(1,-1))){\n"
            "        foreach($fbAx in 0,1){$fbDelta=$fbT[$fbAx]-$fbCur[$fbAx];if($fbDelta){$fbV=[Math]::Sign($fbDelta)*16000;$fbP=170*[Math]::Abs($fbDelta)\n"
            "          if($fbAx){& $fbIn 0 $fbV ($fbP+600)}else{& $fbIn $fbV 0 ($fbP+600)};Start-Sleep -Milliseconds $fbP;& $fbIn 0 0 900}};$fbCur=@($fbT[0],$fbT[1])\n"
            "        for($fbK=0;$fbK-lt3-and!$fbHit;$fbK++){$fbA=& $fbAim;if($fbA-and$fbA.aim){$fbSeen+=$fbA.aim;if($fbA.aim-eq$fbHandle){$fbHit++}};& $fbIn 0 0 900}\n"
            "        if($fbHit){break}}\n"
            "       & $fbIn 0 0 250;Start-Sleep -Milliseconds 350\n")
n = s.count(old_hold)
assert n == 2, n
s = s.replace(old_hold, new_hold)
rep("$row.farReach.spots+=[pscustomobject]@{offset=$fbOff;at=@($fbPx,$fbPy);yaw=$fbYaw;aimed=@($fbSeen|Select-Object -Unique);hit=$fbHit}",
    "$row.farReach.spots+=[pscustomobject]@{offset=$fbOff;at=@($fbPx,$fbPy);yaw=$fbYaw;aimed=@($fbSeen|Select-Object -Unique);hit=$fbHit;sweep=@($fbCur[0],$fbCur[1])}", 2)
rep("        try{$fbLt.WaitForExit(3000)|Out-Null}catch{};break}", "        break}", 2)
rep("       try{$fbLt.WaitForExit(4000)|Out-Null}catch{};Start-Sleep -Milliseconds 1500}", "       Start-Sleep -Milliseconds 1500}", 2)
assert '$fbLt' not in s
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1629.ps1').write_bytes(out.encode('utf-8'))
print('ok')
