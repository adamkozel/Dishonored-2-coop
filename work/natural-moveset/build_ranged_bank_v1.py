"""Append native-clock ranged body candidates and hand-local cosmetic tracks."""
import sys,struct,json,hashlib
from pathlib import Path
P=Path(__file__).resolve().parent;sys.path.insert(0,str(P))
from clip_io import *
L=Library(['gun-hand-reference-manifest-v1.json','items-retarget-manifest-v2.json'],'ranged-bank-sources-v1')
OUT=P/'ranged-banks-v1';OUT.mkdir(exist_ok=True);reports=[];tracks=[]
parts=['idle','ooa','fire','reload','equip','unequip']
for role in ('corvo','emily'):
 data=(P/'balanced-crouch-power-banks-v3'/f'{role}-balanced-crouch-power-bank.bin').read_bytes()
 magic,version,n,count,fps,layout=struct.unpack_from('<8sIIIIQ',data);assert magic==b'D2MOVE28'and count==201
 bank=bytearray(struct.pack('<8sIIIIQ',b'D2MOVE29',29,n,213,fps,layout)+data[32:]);rig=rig_for(role)
 grip=[qts(struct.unpack_from('<7f',data,32+24+j*28))for j in range(n)];fingers=[];sources=[]
 for j in range(n):
  k=j
  while k>=0 and k!=16:k=rig.joints[k]['parent']
  if k==16 and j!=16 and 'helper'not in rig.joints[j]['nativeName']:fingers.append(j)
 for kind in ('gun','crossbow'):
  loaded={part:L.load(role,kind+'_'+part)for part in ['idle','ooa','fire','equip','unequip','reload_in','reload_loop','reload_out']}
  attachment={part:[[qts(q)]for q in m['props'][0]['attachment_track']]for part,(m,fs)in loaded.items()}
  durations=[loaded['idle'][0]['duration'],.5,.666,1.5 if kind=='gun'else .9,.533,.333]
  for slot,part in enumerate(parts):
   duration=durations[slot];used=[part]if part!='reload'else ['reload_in','reload_loop','reload_out']
   def authored(u):
    phase=u;sub=part
    if part=='reload':
     t=u*duration;middle=duration-.666
     if t<.333:sub='reload_in';phase=t/.333
     elif t<duration-.333:sub='reload_loop';phase=(t-.333)/middle
     else:sub='reload_out';phase=(t-(duration-.333))/.333
    pose=sample(loaded[sub][1],phase)
    for j in fingers:pose[j]=grip[j].copy()
    pose[17]=grip[17].copy();preview_helpers(rig,pose)
    return pose,row(sample(attachment[sub],phase)[0])
   sampled=[authored(f/119)for f in range(120)];poses=[v[0]for v in sampled];track=[v[1]for v in sampled]
   index=201+(0 if kind=='gun'else 6)+slot;bank.extend(struct.pack('<IIIIff',index,121,0,0,0.,duration))
   for pose in poses+[poses[0]]:
    assert max((pose[j].translation-rig.bind[j].translation).length for j in range(3,27)if j!=17)<1e-5
    for mat in pose:bank.extend(struct.pack('<7f',*row(mat)))
   provenance=[loaded[s][0]['sha256']for s in used]
   sources.append(dict(clip=index,kind=kind,part=part,duration=duration,sources=provenance))
   tracks.append(dict(role=role,kind=kind,part=part,clip=index,frames=track))
   preview=[authored(f/max(1,round(duration*60)))[0]for f in range(max(1,round(duration*60))+1)]
   L.save(rig,role,'ranged_native_'+kind+'_'+part,preview,[identity()for _ in preview],'ranged_and_items',
    'Whole-body native acting with hand-local first-person references. Source scene controls time. Native movement owns root; no camera wrist anchoring or damage events. Standing base-weapon runtime experiment; context/upgrade coverage pending.',provenance,native_duration_ms=round(duration*1000))
 path=OUT/f'{role}-ranged-bank.bin';path.write_bytes(bank)
 reports.append(dict(role=role,bank=str(path.relative_to(P)),sha256=hashlib.sha256(bank).hexdigest(),format='D2MOVE29',clips=213,
  prior_payload_unchanged=bank[32:len(data)]==data[32:],sources=sources,runtime_verified=False,visual_accepted=False))
L.finish('ranged-bank-source-manifest-v1.json')
(P/'ranged-bank-manifest-v1.json').write_text(json.dumps(reports,indent=2))
(P/'ranged-hand-tracks-v1.json').write_text(json.dumps(tracks,indent=2))
