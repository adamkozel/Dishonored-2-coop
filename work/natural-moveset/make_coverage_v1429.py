"""1429 (#11 power_interruptions_and_no_mana): Record-Coverage-v1403.ps1 with 'labpowerhit', a power aim interrupted by a
hit. The source selects its aimed power (Corvo Blink, Emily Far Reach), holds the trigger for 2.6 s without blocking the
case loop, and 1 s into the aim the lab-only sword hit (coop_lab_hit sword front, 1214dl) lands on it. Natively the hit
stuns the source and cancels the aim. The case passes when the partner presented the aim, then the stun, and the power
pose is gone after the hit (no orphaned power presentation). Generated by make_coverage_v1429.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-Coverage-v1403.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1429 (#11): 'labpowerhit' - an aimed power interrupted by a lab sword hit. Generated by make_coverage_v1429.py.\n" + s[first:]
rep("'labblastleft','labblastright'", "'labblastleft','labblastright','labpowerhit'", 3)
rep("labblastright=11000;", "labblastright=11000;labpowerhit=12000;")
rep("     labblastright=@(@(600,'hold','on'),@(1500,'watchmid',9000),@(2500,'selfcmd','coop_lab_hit blast right'),@(10000,'hold','off'));",
    "     labblastright=@(@(600,'hold','on'),@(1500,'watchmid',9000),@(2500,'selfcmd','coop_lab_hit blast right'),@(10000,'hold','off'));\n"
    "     labpowerhit=@(@(600,'hold','on'),@(800,'named',$(if($source-eq'host'){'models/powers/blink/blink.inventoryitem'}else{'models/powers/grapple/grapple.inventoryitem'})),@(1500,'watchmid',9500),@(2400,'ltasync',2600),@(3400,'selfcmd','coop_lab_hit sword front'),@(10500,'hold','off'));")
rep("'selfcmd'{C $source $d[2]}",
    "'selfcmd'{C $source $d[2];$row.labHitAt=$t};'ltasync'{$row.aimAt=$t;$null=Start-Process (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-File',\"$lab/Send-D2Input.ps1\",'-Role',$source,'-LeftTrigger','255','-DurationMs',[string]$d[2]) -WindowStyle Hidden -PassThru}")
rep("      if(!$shown.Count){throw 'No stun presented at stun weight'}",
    "      if(!$shown.Count){throw 'No stun presented at stun weight'}\n"
    "      if($case-eq'labpowerhit'){$aim=@($samples|Where-Object {[double]$_.powerWeight-gt.5-and$_.ms-lt$row.labHitAt+300});$row.aimVariants=@($aim|ForEach-Object {[int]$_.powerVariant}|Sort-Object -Unique)\n"
    "       $after=@($samples|Where-Object {$_.ms-ge$row.labHitAt+1500});$row.powerAfterMax=$(if($after.Count){($after|Measure-Object -Property powerWeight -Maximum).Maximum}else{$null})\n"
    "       if(!$aim.Count){throw 'No power aim presented before the hit'};if($null-eq$row.powerAfterMax-or[double]$row.powerAfterMax-gt.05){throw \"Power presentation left after the hit (max weight $($row.powerAfterMax))\"}\n"
    "       $row.checks.Add(\"Aim presented (variants $($row.aimVariants-join ',')), interrupted by the hit; no power presentation 1.5 s after it\")}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-Coverage-v1429.ps1').write_bytes(out.encode('utf-8'))
print('ok')
