"""1541 (#11 enemy_body_size_variants, knocked down): Record-MissionCoverage-v1539.ps1 with -TrackPartner: every loop after
the press the source's own position (probe --player) and the peer's view of it (status remotePosition and the presented
probeRenderPosition) are saved as <key>-track.json. 1538a: in Emily's own view she chokes the overseer at her feet
(choke_knockdown_back) and the host's body was moved to her victim's root, yet in Corvo's window she bends over about
1.5 m from the body; the track shows whether her presented body or her streamed root is off during the scene.
Generated by make_mission_coverage_v1541.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1539.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$KnockLanded,[string]$SeekWindow='')", "[switch]$KnockLanded,[string]$SeekWindow='',[switch]$TrackPartner)")
first = s.index('\n') + 1
s = s[:first] + "# 1541 (#11): -TrackPartner records the source and its presented body after the press. Generated by make_mission_coverage_v1541.py.\n" + s[first:]
rep("$knock=[Collections.Generic.List[object]]::new();$kp=$null;$wins=[Collections.Generic.List[object]]::new()\n",
    "$knock=[Collections.Generic.List[object]]::new();$kp=$null;$wins=[Collections.Generic.List[object]]::new();$track=[Collections.Generic.List[object]]::new()\n")
anchor = "      if($SeekWindow-and$PlaceAt-and!$row.seek-and!$acted-and$t-ge(650+$delay)){"
rep(anchor,
    "      if($TrackPartner-and$acted){$sp4=try{(Q $source '--player').candidatePosition}catch{$null};$ps4=try{S $peer}catch{$null}\n"
    "       $track.Add([ordered]@{t=$t;source=$sp4;peerRemote=$(if($ps4){$ps4.remotePosition}else{$null});peerRender=$(if($ps4){$ps4.probeRenderPosition}else{$null})})}\n" + anchor)
rep("if($WindowProbe){Save \"$out/$key-window.json\" @($wins);",
    "if($TrackPartner){Save \"$out/$key-track.json\" @($track);$row.trackSamples=$track.Count}\n     if($WindowProbe){Save \"$out/$key-window.json\" @($wins);")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1541.ps1').write_bytes(out.encode('utf-8'))
print('ok')
