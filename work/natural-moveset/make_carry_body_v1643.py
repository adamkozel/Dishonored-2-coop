from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-CarryBody-v1642.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
lines = s.split('\n')
lines.insert(2, "# 1643 (#117): -DominoLink links the two tutorial guards before the takedown and samples guard 1 after it. Generated by make_carry_body_v1643.py.")
s = '\n'.join(lines)
rep("[switch]$PossessCorpse)", "[switch]$PossessCorpse,[switch]$DominoLink)")
helper = (
    "$domAim={param($target,$stand)\n"
    " if($stand){C $source ('setviewpos {0} {1} {2} 90 0' -f (F $stand[0]),(F $stand[1]),(F ([double]$stand[2]+1.7)));Start-Sleep -Milliseconds 700}\n"
    " $pl=Q $source '--player';$me=$pl.candidatePosition;$eye=[double]$pl.nativeViewPosition[2]\n"
    " $yaw=[Math]::Atan2([double]$target[1]-[double]$me[1],[double]$target[0]-[double]$me[0])*180/[Math]::PI;$h=[Math]::Max(.5,[Math]::Sqrt([Math]::Pow([double]$target[0]-[double]$me[0],2)+[Math]::Pow([double]$target[1]-[double]$me[1],2)))\n"
    " $pitch=[Math]::Atan2($eye-([double]$target[2]+1.3),$h)*180/[Math]::PI\n"
    " C $source ('setviewpos {0} {1} {2} {3} 0' -f (F $me[0]),(F $me[1]),(F ([double]$me[2]+1.7)),(F $yaw));Start-Sleep -Milliseconds 300;& \"$PSScriptRoot/Set-ObserverPitch.ps1\" -Role $source -Pitch $pitch -Quick|Out-Null\n"
    " [ordered]@{target=$target;stand=$me;yaw=$yaw;pitch=$pitch;distance=$h}}\n")
rep("function Save($p,$v){", helper + "function Save($p,$v){")
rep("   if($GrantNamed){$row.granted=@();",
    "   if($DominoLink){if($source-ne'client'){throw 'Domino is Emily''s power'}\n"
    "    C $source 'coop_grant_named models/powers/phantasmallink/phantasmal_link.inventoryitem';Start-Sleep -Milliseconds 1800;$row.dominoAims=@()\n"
    "    $dlG=@((Q $source '--world-npcs').npcs|Where-Object {$_.spawnerName-eq'ld_spawner_guard_tutorial_2'-and[Math]::Abs([double]$_.position[2]-66.4)-lt.6});if(!$dlG.Count){throw 'Domino: tutorial guard 2 not on the upper floor'}\n"
    "    C $source 'setviewpos -44.39 -153.27 68.1 90 0';Start-Sleep -Milliseconds 600;$row.dominoAims+=(& $domAim $dlG[0].position $null);& \"$lab/Send-D2Input.ps1\" -Role $source -LeftTrigger 255 -DurationMs 1800|Out-Null;Start-Sleep -Milliseconds 1500\n"
    "    $dlG=@((Q $source '--world-npcs').npcs|Where-Object {$_.spawnerName-eq'ld_spawner_guard_tutorial_1'-and[double]$_.position[2]-ge60.5-and[double]$_.position[2]-le67});if(!$dlG.Count){throw 'Domino: tutorial guard 1 not found'}\n"
    "    $dlP=$dlG[0].position;$row.dominoAims+=(& $domAim $dlP @([double]$dlP[0],([double]$dlP[1]-3.5),[double]$dlP[2]));& \"$lab/Send-D2Input.ps1\" -Role $source -LeftTrigger 255 -DurationMs 1800|Out-Null;Start-Sleep -Milliseconds 2000\n"
    "    $row.dominoLinks=try{(S $source '.domino-world.json')}catch{$null}}\n"
    "   if($GrantNamed){$row.granted=@();")
rep("   $gpSeries=[Collections.Generic.List[object]]::new();$gpW=[Diagnostics.Stopwatch]::StartNew()\n",
    "   if($DominoLink){$dlSeries=[Collections.Generic.List[object]]::new();$dlW=[Diagnostics.Stopwatch]::StartNew()\n"
    "    while($dlW.ElapsedMilliseconds-lt8000){$dlRow=[ordered]@{ms=$dlW.ElapsedMilliseconds}\n"
    "     foreach($dlR in 'host','client'){$dlN=@($(try{(Q $dlR '--world-npcs').npcs}catch{@()})|Where-Object {$_.spawnerName-eq'ld_spawner_guard_tutorial_1'})\n"
    "      $dlRow[$dlR]=$(if($dlN.Count){$dlH=try{Q $dlR '--health' $dlN[0].handle}catch{$null};[ordered]@{present=$true;position=$dlN[0].position;current=$dlH.current;suppressed=$dlH.ownerSuppressed}}else{[ordered]@{present=$false}})}\n"
    "     $dlSeries.Add([pscustomobject]$dlRow);Start-Sleep -Milliseconds 700}\n"
    "    Save \"$out/$key-domino-guard1.json\" @($dlSeries);$dlEnd=$dlSeries[$dlSeries.Count-1]\n"
    "    $row.checks.Add(\"Domino-linked guard 1 after guard 2's takedown: host health $($dlEnd.host.current) (suppressed $($dlEnd.host.suppressed)), client health $($dlEnd.client.current) (suppressed $($dlEnd.client.suppressed))\")}\n"
    "   $gpSeries=[Collections.Generic.List[object]]::new();$gpW=[Diagnostics.Stopwatch]::StartNew()\n")
