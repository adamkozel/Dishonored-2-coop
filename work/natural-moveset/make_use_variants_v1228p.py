"""1228p (#11 key_use): Test-UseVariants-v1228o.ps1 with -UseSources choosing which sources run the Dunwall use cases.
In use-variants-dunwall-v1228w the host's case left the host body standing at the ring lock, so the client's case
presented nothing (the partner overlapped the observer: weight 0 throughout), and the free camera 2.4 m behind the
source stood outside the tower wall (the video shows only sky). One source per take keeps the observer body parked at
its fixture spot; -Back/-Side then place the camera along the wall. Generated by make_use_variants_v1228p.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-UseVariants-v1228o.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)

rep("# 1228o (#11):", "# 1228p (#11): -UseSources picks the sources of the Dunwall use cases (one per take keeps the observer parked).\n# Generated by make_use_variants_v1228p.py.\n# 1228o (#11):")
rep("[switch]$FreeCam,", "[switch]$FreeCam,[string[]]$UseSources=@('host','client'),")
for kind, line in (('locks', "UseCase host client $locks 5 'ring_locker|lock'\n  UseCase client host $locks 5 'ring_locker|lock'}"),
                   ('taps', "UseCase host client @('esc_env_rich_sink_tap_01_1') 4 'tap'\n  UseCase client host @('esc_env_rich_sink_tap_01_1') 4 'tap'}"),
                   ('window', "UseCase host client @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional\n  UseCase client host @('ld_rich_small_gp_window_handle_37') 1 'window_handle' -Optional}"),
                   ('door', "UseCase host client @('ld_door_350cm_int_rich_wood_01') 1 'door'\n  UseCase client host @('ld_door_350cm_int_rich_wood_01') 1 'door'}")):
    host, client = line.split('\n  ')
    rep(line, f"if('host'-in$UseSources){{{host}}}\n  if('client'-in$UseSources){{{client[:-1]}}}}}")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-UseVariants-v1228p.ps1').write_bytes(out.encode('utf-8'))
print('ok')
