"""1273b (#14 real grenade, 1214au): Test-GrenadeBoundGuard-v1273.ps1 with a real native grenade granted in product mode
(coop_grant_item grenade: native inventory add, then the native equip) instead of the isolated fixture, which refuses
product mode (1273a: unsupported_scope_or_item_owned). -Thrower host|client picks who throws at the upper-floor guard from
-Distance metres (LT held, native release). Pass (runtime): the guard's health drops or it dies, and the other world ends
in the same state."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-GrenadeBoundGuard-v1273.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='grenade-bound-guard-v1273a',[string]$Candidate='candidate-npc-combat-v1214w',",
    "[string]$Take='grenade-real-v1273b',[string]$Candidate='candidate-npc-combat-v1214au',[ValidateSet('host','client')][string]$Thrower='host',")
rep("# 1273 (stage 4, #14, 1214w)", "# 1273b (#14, 1214au): real grenade granted in product mode (coop_grant_item), -Thrower host|client. Generated by\n# make_grenade_real_v1273b.py.\n# 1273 (stage 4, #14, 1214w)")
rep("""   C host 'coop_grenade_fixture 12000';$fw=[Diagnostics.Stopwatch]::StartNew()
   do{Start-Sleep -Milliseconds 50;$f=S host '.grenade-fixture.json'}while($f.result-ne'native_grenade_ready'-and$fw.ElapsedMilliseconds-lt2500)
   if($f.result-ne'native_grenade_ready'){throw "Grenade fixture not ready ($($f.result))"}
   I host X 1500;Start-Sleep -Milliseconds 1900;I host X 650;Start-Sleep -Milliseconds 1350
   $held=Q host '--player-grenade';if(!$held.equipped-or$held.quantity-ne1){throw 'Native grenade not selected'}""",
"""   C $Thrower 'coop_grant_item grenade';$fw=[Diagnostics.Stopwatch]::StartNew()
   do{Start-Sleep -Milliseconds 100;$f=(S $Thrower '.observer-camera.json').itemGrant}while($f.result-notin'granted_grenade_equipped','grenade_slot_occupied','grenade_equip_timeout','grenade_read_failed','refused_not_gameplay'-and$fw.ElapsedMilliseconds-lt4000)
   $row.grant=$f;if($f.result-ne'granted_grenade_equipped'){throw "Grenade grant not equipped ($($f.result))"};Start-Sleep -Milliseconds 800
   $held=Q $Thrower '--player-grenade';if(!$held.equipped-or$held.quantity-lt1){throw 'Native grenade not selected'}""")
rep("""   $g=Guard host;$vx=-33-""", """   $g=Guard $Thrower;$vx=-33-""")
rep("""   C host ('setviewpos {0} {1} {2} {3} 0' -f (F ([double]$g.position[0]-$Distance*$fx))""", """   C $Thrower ('setviewpos {0} {1} {2} {3} 0' -f (F ([double]$g.position[0]-$Distance*$fx))""")
rep("""   try{& "$PSScriptRoot/Set-ObserverPitch.ps1" -Role host -Pitch $Pitch -Quick|Out-Null}catch{}""", """   try{& "$PSScriptRoot/Set-ObserverPitch.ps1" -Role $Thrower -Pitch $Pitch -Quick|Out-Null}catch{}""")
rep("""   & "$lab/Send-D2Input.ps1" -Role host -LeftTrigger 255 -DurationMs 1300|Out-Null""", """   & "$lab/Send-D2Input.ps1" -Role $Thrower -LeftTrigger 255 -DurationMs 1300|Out-Null""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-GrenadeReal-v1273b.ps1').write_bytes(out.encode('utf-8'))
print('ok')
