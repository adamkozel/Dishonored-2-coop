"""1258j (#9, 1214aj): Test-Counterattack-v1258i.ps1 with a release before the attack. In take 1258q the cycle caught four
blocked hits but no slash ever played: the attack packet replaced the held block in the same frame and the game ignored it
(1258g, which attacked after the block had expired, slashed every cycle). The cycle now publishes neutral input for 60 ms
before the attack (200 ms)."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Test-Counterattack-v1258i.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[string]$Take='counterattack-v1258q'", "[string]$Take='counterattack-v1258r'")
rep("# 1258i (#9, 1214aj): hold block",
    "# 1258j (#9, 1214aj): neutral input for 60 ms between the block and the attack (1258q: an attack replacing a held block in\n"
    "# the same frame never slashed). Generated by make_counterattack_v1258j.py.\n"
    "# 1258i (#9, 1214aj): hold block")
rep("""     & "$lab/Send-D2Input.ps1" -Role $source -RightTrigger 255 -DurationMs 150|Out-Null;Start-Sleep -Milliseconds 150;& "$lab/Send-D2Input.ps1" -Role $source -DurationMs 100|Out-Null}""",
"""     & "$lab/Send-D2Input.ps1" -Role $source -DurationMs 100|Out-Null;Start-Sleep -Milliseconds 60
     & "$lab/Send-D2Input.ps1" -Role $source -RightTrigger 255 -DurationMs 200|Out-Null;Start-Sleep -Milliseconds 200;& "$lab/Send-D2Input.ps1" -Role $source -DurationMs 100|Out-Null}""")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Test-Counterattack-v1258j.ps1').write_bytes(out.encode('utf-8'))
print('ok')
