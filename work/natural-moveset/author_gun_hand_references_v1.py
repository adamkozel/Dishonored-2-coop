"""Native full-body gun acting plus hand-relative FP references, no wrist anchors."""
import sys,json
from pathlib import Path
P=Path(__file__).resolve().parent;sys.path.insert(0,str(P))
from clip_io import *
from finger_reference import HandReference,SR,SN
from edge_data import poses as edge_poses
L=Library(['library-retarget-manifest.json'],'gun-hands-authored-v1')
refs=read(P/'fp-gun-reference-manifest-v1.json')['rows'];calibrations=[]
crossbows=read(P/'items-retarget-manifest-v2.json')
for role in ('corvo','emily'):
 rig=rig_for(role);hand=HandReference(rig)
 donors={a:L.load(role,a)for a in ('sword_gun_idle','sword_gun_fire','sword_gun_reload','sword_gun_equip_fast','sword_gun_unequip')}
 for part in ('idle','equip','unequip','fire','ooa','reload_in','reload_loop','reload_out'):
  alias='ply_leftarm_gun_'+part
  ref=next(r for r in refs if alias in r['aliases'] and '/'+role+'/' in r['asset'])
  edge=edge_poses(P/ref['sample_file']);assert edge['sha256']==ref['sample_sha256']
  fp=[[qts(v)for v in f]for f in edge['frames']];duration=(len(fp)-1)/edge['fps'];count=max(2,round(duration*60)+1)
  donor='sword_gun_equip_fast'if part=='equip'else'sword_gun_unequip'if part=='unequip'else'sword_gun_reload'if part.startswith('reload')else'sword_gun_fire'if part in ('fire','ooa')else'sword_gun_idle'
  dm,body=donors[donor];poses=[];attachments=[]
  for f in range(count):
   u=f/(count-1);phase=u
   if part.startswith('reload_'):
    a,b={'reload_in':(0,.3),'reload_loop':(.3,.7),'reload_out':(.7,1)}[part];phase=a+(b-a)*u
   pose=sample(body,phase,part in ('idle','reload_loop'))
   if part=='ooa':pose=blend(sample(donors['sword_gun_idle'][1],u,True),pose,.18)
   reference=sample(fp,u,part in ('idle','reload_loop'));hand.apply(pose,reference);preview_helpers(rig,pose)
   fg=SR.fk(reference);attachment=hand.invcal.to_4x4()@fg[4].inverted()@fg[SN['left_hand_attachment_jnt']]
   poses.append(pose);attachments.append(row(attachment))
  source=dict(body_alias=donor,body_sha256=dm['sha256'],hand_asset=ref['asset'],hand_sample_sha256=ref['sample_sha256'])
  L.save(rig,role,'gun_'+part,poses,[identity()for _ in poses],'ranged_and_items',
   'Native whole-body gun acting with native finger articulation and hand-local prop reference; no camera-space wrist target. Gameplay binding and remote mechanism animation pending.',source,
   props=[dict(kind='gun_'+role,parent_joint=9,attachment_track=attachments,events=False)])
  if part=='idle':calibrations.append(dict(role=role,kind='gun',attachment=attachments[0],source=source,body_binary=L.reports[-1]['binary']))
 crossbow=next(r for r in crossbows if r['role']==role and r['selection']['alias']=='crossbow_idle')
 calibrations.append(dict(role=role,kind='crossbow',attachment=crossbow['props'][0]['attachment_track'][0],source=crossbow['source'],body_binary=crossbow['binary']))
L.finish('gun-hand-reference-manifest-v1.json')
lines=['#pragma once','// Generated by author_gun_hand_references_v1.py. Idle hand-local calibration only.',
 '// Native fingers/prop reference; never fixes the wrist or changes body bone lengths.',
 'inline bool rangedPropIdleCalibration(unsigned character,unsigned kind,float* offset,float* axis){']
for c in calibrations:
 m=qts(c['attachment']);offset=list(m.translation);axis=[m[r][col]for col in range(3)for r in range(3)]
 values=lambda xs:','.join(format(float(v),'.9f')+'f'for v in xs)
 lines.append(' if(character==%d&&kind==%d){const float p[]={%s},r[]={%s};std::copy(p,p+3,offset);std::copy(r,r+9,axis);return true;}'%((1 if c['role']=='corvo'else 2),(1 if c['kind']=='gun'else 2),values(offset),values(axis)))
lines+=[' return false;','}']
(P.parent.parent/'outputs/d2-coop-lab/src/ranged_prop_calibration.h').write_text('\n'.join(lines)+'\n')
(P/'ranged-prop-calibration-v1.json').write_text(json.dumps(dict(scope='Idle calibration experiment; moving action-specific hand tracks and mechanism playback not integrated yet.',calibrations=calibrations),indent=2))
print('AUTHORED_GUN_HAND_REFERENCES 16 / CALIBRATIONS 4',flush=True)
