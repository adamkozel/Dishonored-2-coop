"""1567 (#11 enemy_body_size_variants, seated): Record-MissionCoverage-v1566.ps1 with -ChokeProbe: the native choke sensor
(probe --choke-sensor, 1214er: arkCpntPlayerSensorChoke +0x50 target handle and name, +0x54 flag) is read every loop
from 250 ms until one sample after the press and saved per case (<key>-choke.json; the row keeps chokeAtPress). Survey
1563a showed seated NPCs pass every NPC-side gate of the takedown eligibility, yet no seated NPC was ever offered a
choke: this shows whether the sensor ever takes a seated NPC as its target, against a standing control.
Generated by make_mission_coverage_v1567.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1566.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$PlaceBoth)", "[switch]$PlaceBoth,[switch]$ChokeProbe)")
first = s.index('\n') + 1
s = s[:first] + "# 1567 (#11): -ChokeProbe samples the native choke sensor until the press. Generated by make_mission_coverage_v1567.py.\n" + s[first:]
rep("$wins=[Collections.Generic.List[object]]::new();", "$wins=[Collections.Generic.List[object]]::new();$chokes=[Collections.Generic.List[object]]::new();")
anchor = "      if($WindowProbe-and$t-ge250-and(!$acted-or!$row.windowAfter)){"
rep(anchor,
    "      if($ChokeProbe-and$t-ge250-and(!$acted-or!$row.chokeAfter)){$cs=try{Q $source '--choke-sensor'}catch{$null}\n"
    "       if($cs){$chokes.Add([ordered]@{t=$t;acted=[bool]$acted;enabled=$cs.enabled;target=$cs.target;targetName=$cs.targetName;flag54=$cs.flag54;value58=$cs.value58;value5c=$cs.value5c})\n"
    "        if($acted){$row.chokeAfter=$t}else{$row.chokeAtPress=[ordered]@{t=$t;target=$cs.target;targetName=$cs.targetName;flag54=$cs.flag54}}}}\n" + anchor)
rep('if($WindowProbe){Save "$out/$key-window.json" @($wins)',
    'if($ChokeProbe){Save "$out/$key-choke.json" @($chokes);$row.chokeSamples=$chokes.Count;$row.chokeTargeted=@($chokes|Where-Object {$_.targetName}).Count}\n     if($WindowProbe){Save "$out/$key-window.json" @($wins)')
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1567.ps1').write_bytes(out.encode('utf-8'))
print('ok')
