"""1533 (#11 wall_and_window_variants): Record-MissionCoverage-v1530.ps1 with the native window sensor read on the source
(probe --window-sensor, 1214em) every loop from 250 ms until the press and once after it, saved as <key>-window.json
and summarised in the row (target named, angle, sill, grounded at the press). Window stands now come from the sensor
scan 1527 (a stand the sensor accepts; the target placed 0.7 m past its window point, -PlaceAt with -Behind set to the
stand's distance), so a failed press says which native condition was missing.
Generated by make_mission_coverage_v1533.py."""
from pathlib import Path
N = Path(__file__).resolve().parent
src = (N / 'Record-MissionCoverage-v1530.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
rep("[switch]$KnockProbe,[switch]$KnockOnGround)", "[switch]$KnockProbe,[switch]$KnockOnGround,[switch]$WindowProbe)")
first = s.index('\n') + 1
s = s[:first] + "# 1533 (#11): -WindowProbe reads the native window sensor on the source. Generated by make_mission_coverage_v1533.py.\n" + s[first:]
rep("     $replaced=$false;$npcMid=$false;$knock=[Collections.Generic.List[object]]::new();$kp=$null\n",
    "     $replaced=$false;$npcMid=$false;$knock=[Collections.Generic.List[object]]::new();$kp=$null;$wins=[Collections.Generic.List[object]]::new()\n")
anchor = "      if(!$acted-and$t-ge(700+$delay)-and(!$KnockdownSettle-or$t-ge4400)){"
rep(anchor,
    "      if($WindowProbe-and$t-ge250-and(!$acted-or!$row.windowAfter)){$ws=try{Q $source '--window-sensor'}catch{$null}\n"
    "       if($ws){$wins.Add([ordered]@{t=$t;acted=[bool]$acted;target=$ws.target;targetName=$ws.targetName;hasPoint=$ws.hasPoint;point=$ws.point;sill=$ws.sill;angleOk=$ws.angleOk;sillOk=$ws.sillOk;grounded=$ws.grounded;position=$ws.position;forward=$ws.forward})\n"
    "        if($acted){$row.windowAfter=$t}else{$row.windowAtPress=[ordered]@{t=$t;targetName=$ws.targetName;hasPoint=$ws.hasPoint;sill=$ws.sill;angleOk=$ws.angleOk;sillOk=$ws.sillOk;grounded=$ws.grounded}}}}\n"
    + anchor)
rep("if($KnockProbe){Save \"$out/$key-knock.json\" @($knock);",
    "if($WindowProbe){Save \"$out/$key-window.json\" @($wins);$row.windowSamples=$wins.Count;$row.windowAvailable=@($wins|Where-Object {$_.targetName-and$_.hasPoint-and$_.angleOk-and$_.sillOk-and$_.grounded}).Count}\n"
    "     if($KnockProbe){Save \"$out/$key-knock.json\" @($knock);")
out = s.replace('\n', '\r\n') if crlf else s
(N / 'Record-MissionCoverage-v1533.ps1').write_bytes(out.encode('utf-8'))
print('ok')
