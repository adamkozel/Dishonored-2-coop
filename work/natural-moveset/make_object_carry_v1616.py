N = Path(__file__).resolve().parent
src = (N / 'Probe-ObjectCarry-v1478.ps1').read_bytes().decode('utf-8')
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')
def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (s.count(old), old[:90])
    s = s.replace(old, new)
first = s.index('\n') + 1
s = s[:first] + "# 1616 (#115): the farreachbottle case dumps arkCpntPowerGrapple (UsePower +0x60). Generated by make_object_carry_v1616.py.\n" + s[first:]
anchor = "      if($sa.id-eq84-and!$grappleDumped){"
