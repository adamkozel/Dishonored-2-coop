"""1616 (#115): Probe-ObjectCarry-v1478.ps1 whose 'farreachbottle' case also dumps the Far Reach power component. The
UsePower state (63) points at arkCpntPowerGrapple at +0x60; the component belongs to the power item, not to the player,
so 1454b's dump of the player's grapple sensors never held the pulled bottle (its handle was in none of them).
The power component is dumped at every UsePower or GrabGrappledEntity (84) sample (up to 6), to be searched afterwards
for the bottle's handle or pointer. The case's dump cap rises from 4 to 14, so the dumps reach the pull's state 84
(object-carry-v1616a stopped at 4, all during the aim). Generated by make_object_carry_v1616.py."""
