scene=bpy.data.scenes['D2_Mixamo_Source'];rig=bpy.data.objects['Armature']
native=json.loads((root/'native-corvo.json').read_text(encoding='utf-8-sig'))
joints=native['joints']
assert len(joints)==215 and joints[2]['nativeName']=='center_root_jnt'
mapping={2:'Hips',3:'Spine',4:'Spine1',5:'Spine2',6:'LeftShoulder',7:'LeftArm',8:'LeftForeArm',9:'LeftHand',11:'Neck',12:'Head',13:'RightShoulder',14:'RightArm',15:'RightForeArm',16:'RightHand',19:'LeftUpLeg',20:'LeftLeg',21:'LeftFoot',22:'LeftToeBase',23:'RightUpLeg',24:'RightLeg',25:'RightFoot',26:'RightToeBase'}
C=Matrix.Rotation(math.pi/2,4,'Z') # Blender donor faces -Y; native character faces +X.
def rigid(m):
    r=m.to_quaternion().to_matrix().to_4x4();r.translation=m.translation;return r
rest={j:rigid(C@rig.matrix_world@rig.data.bones['mixamorig:'+n].matrix_local) for j,n in mapping.items()}
bind=[];global_bind=[]
for b in joints:
    q=b['bindLocalQTS'];m=Quaternion((q[3],q[0],q[1],q[2])).normalized().to_matrix().to_4x4();m.translation=Vector(q[4:7])
    bind.append(m);global_bind.append(m if b['parent']<0 else global_bind[b['parent']]@m)
# The native arms use an A-pose and the donor a T-pose. Align upper-arm and
# forearm rest directions before applying donor motion; preserve native lengths.
arm_children={7:8,8:9,14:15,15:16}
corrections={j:Matrix.Identity(4) for j in mapping}
for j,ch in arm_children.items():
    a=(global_bind[ch].translation-global_bind[j].translation).normalized()
    b=(rest[ch].translation-rest[j].translation).normalized()
    corrections[j]=a.rotation_difference(b).to_matrix().to_4x4()
frames=[];hip_samples=[]
for f in range(1,64):
    scene.frame_set(f);bpy.context.view_layer.update()
    pose={j:rigid(C@rig.matrix_world@rig.pose.bones['mixamorig:'+n].matrix) for j,n in mapping.items()}
    hip_samples.append(pose[2].translation.copy());frames.append(pose)
mean=sum(hip_samples,Vector())/len(hip_samples)
scale=(global_bind[19].translation-global_bind[21].translation).length/(rest[19].translation-rest[21].translation).length
baked=[];checks=[]
for f,pose in enumerate(frames):
    local=[m.copy() for m in bind];glob=[]
    for j,b in enumerate(joints):
        p=b['parent']
        if j in mapping:
            desired=pose[j].to_3x3()@rest[j].to_3x3().inverted()@corrections[j].to_3x3()@global_bind[j].to_3x3()
            rot=glob[p].to_3x3().inverted()@desired if p>=0 else desired
            m=rot.to_quaternion().normalized().to_matrix().to_4x4();m.translation=bind[j].translation
            if j==2:
                delta=(pose[2].translation-rest[2].translation)*scale
                delta.x=(pose[2].translation.x-mean.x)*scale;delta.y=(pose[2].translation.y-mean.y)*scale
                m.translation+=delta
            local[j]=m
        glob.append(local[j] if p<0 else glob[p]@local[j])
    # Native foot proportions differ from the donor. Translate the pelvis only
    # to put the lowest toe at the native bind floor; never stretch a limb.
    floor=min(global_bind[22].translation.z,global_bind[26].translation.z)
    shift=floor-min(glob[22].translation.z,glob[26].translation.z)
    assert abs(shift)<.25, ('unexpected floor correction',f,shift)
    local[2].translation.z+=shift
    row=[]
    for j in mapping:
        q=local[j].to_quaternion().normalized();row.append([q.x,q.y,q.z,q.w,*local[j].translation])
    baked.append(row);checks.append({'frame':f+1,'floor_adjustment':shift,'pelvis_z':local[2].translation.z})
data={'experimental':True,'target':'Corvo custom Doppelganger','target_count':215,'fps':60,'frame_count':len(baked),'duration_seconds':62/60,'indices':list(mapping),'names':{str(j):joints[j]['nativeName'] for j in mapping},'source_names':mapping,'frames':baked,'translation_scale':scale,'checks':checks,'notes':['Pose-curve override, not native edgeanim conversion.','Network root 0 and anchor 1 are excluded.','Native local bone translations preserved except pelvis height/sway.','Unmapped fingers, attachments, cloth and corrective evaluation remain native.','Source covers a forward gait, not authored idle/transitions/sword actions.']}
(root/'corvo-clip.json').write_text(json.dumps(data,indent=2),encoding='utf-8')
