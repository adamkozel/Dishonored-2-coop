"""Closed NPC fingers and socket remain a coherent grip in both stances.
Reverse the sword around its grip centre, then solve the crouched wrist to
the measured FP blade orientation. Never transplant FP attachment offsets.
Run in Blender; reads saved captures only, writes this experiment directory.
"""
import json, math
from pathlib import Path
from mathutils import Matrix, Quaternion, Vector
p=Path(r'C:/Users/adako/Documents/Codex/2026-10-08/i-x20/work/sword-grip-fit')
ref=p.parent/'crouch-grip-reference';old=p.parent/'mixamo-crouch'
def read(f):return json.loads(f.read_text(encoding='utf-8-sig'))
def mat(v):
 m=Matrix.Identity(4)
 for c in range(4):
  for r in range(3):m[r][c]=v[c*4+r]
 return m
def qts(v):
 m=Quaternion((v[3],v[0],v[1],v[2])).normalized().to_matrix().to_4x4();m.translation=Vector(v[4:7]);return m
def vals(q):return [q.x,q.y,q.z,q.w]
def row(v):return '{'+','.join(f'{x:.9f}f' for x in v)+'}'
reports={}
for char,count,stride in [('corvo',215,2.04),('emily',219,2.05)]:
 d=read(old/f'native-{char}-sword-grip.json')['joints'];native=read(old/f'native-{char}.json')['joints']
 reference=read(ref/'reference-grip-conversion.json')[char]
 socket=mat(d[17]['localPose']);global_socket=mat(d[17]['globalPose'])
 # Handle runs along native socket X. Average the four fingers' proximal
 # locations along this axis; leave radial coordinates on the handle axis.
 cx=sum((global_socket.inverted()@mat(d[i]['globalPose']).translation).x for i in [40,42,44,47])/4
 centre=Vector((cx,0,0));flip=Matrix.Rotation(math.pi,3,'Y')
 reverse=socket.copy();reverse.translation=socket.translation+socket.to_3x3()@(centre-flip@centre)
 reverse_rot=socket.to_3x3()@flip
 for c in range(3):
  for r in range(3):reverse[r][c]=reverse_rot[r][c]
 qb=reference['target_binding'];binding=Quaternion((qb[3],-qb[0],-qb[1],-qb[2])).normalized().to_matrix()
 desired_weapon=Matrix(reference['weapon_model_rotation']);wrist=desired_weapon@(reverse_rot@binding).inverted()
 clip=read(ref/f'{char}-posture100-clip.json');wi=clip['indices'].index(16)
 for frame in clip['frames']:
  local=[qts(j['bindLocalQTS']) for j in native]
  for idx,v in zip(clip['indices'],frame):local[idx]=qts(v)
  global_pose=[]
  for idx,j in enumerate(native):global_pose.append(local[idx] if j['parent']<0 else global_pose[j['parent']]@local[idx])
  frame[wi][:4]=vals((global_pose[15].to_3x3().inverted()@wrist).to_quaternion().normalized())
 h=['#pragma once','// Generated by work/sword-grip-fit/bake_grip.py',f'constexpr unsigned kMixamo{char.title()}Joints[]={{'+','.join(map(str,clip['indices']))+'};',f'constexpr float kMixamo{char.title()}Frames[63][22][7]={{']
 h += ['{'+','.join(row(v) for v in frame)+'},' for frame in clip['frames']];h+=['};']
 (p/f'mixamo_{char}_clip.h').write_text('\n'.join(h)+'\n')
 indices=[17,*range(38,49),*range(63 if count==215 else 60,73 if count==215 else 70)]
 prefix='kMixamoGrip' if char=='corvo' else 'kMixamoEmilyGrip'
 h=['#pragma once','// Matched native finger grip; reverse socket rotates about handle centre.',f'constexpr unsigned {prefix}Joints[]={{'+','.join(map(str,indices))+'};',f'constexpr float {prefix}Rotation[][4]={{']
 h += [row(vals((reverse if idx==17 else mat(d[idx]['localPose'])).to_quaternion().normalized()))+',' for idx in indices];h+=['};']
 h += [f'constexpr float kMixamo{char.title()}StandingWrist[4]='+row(vals(mat(d[16]['localPose']).to_quaternion().normalized()))+';',f'constexpr float kMixamo{char.title()}StandingSocket[4]='+row(vals(socket.to_quaternion().normalized()))+';',f'constexpr float kMixamo{char.title()}StandingSocketPosition[3]='+row(socket.translation)+';',f'constexpr float kMixamo{char.title()}AttachmentPosition[3]='+row(reverse.translation)+';',f'constexpr float kMixamo{char.title()}Stride={stride:.9f}f;']
 (p/f'mixamo_{char}_grip.h').write_text('\n'.join(h)+'\n')
 reports[char]={'grip_axis_center_native_socket':list(centre),'standing_socket':list(socket.translation),'crouch_socket':list(reverse.translation),'centre_error_m':((socket@centre)-(reverse@centre)).length,'weapon_model_rotation':reference['weapon_model_rotation'],'grip_source':f'native-{char}-sword-grip.json','reverse_degrees':180,'stride':stride,'posture':100,'arm_space':70 if char=='corvo' else 50}
(p/'conversion.json').write_text(json.dumps(reports,indent=2));result=reports
