 h+=['};',f'constexpr float kMixamo{char.title()}AttachmentPosition[3]={{'+','.join(f'{x:.9f}f' for x in attach_position)+'};',f'constexpr float kMixamo{char.title()}Stride={stride:.9f}f;']
