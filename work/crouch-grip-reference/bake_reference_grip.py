def read(path):return json.loads(path.read_text(encoding='utf-8-sig'))
def mat(v):
 m=Matrix.Identity(4)
 for c in range(4):
  for r in range(3):m[r][c]=v[c*4+r]
 return m
def root(v):
 m=Matrix.Identity(4);m.translation=Vector(v[:3])
 for c in range(3):
  for r in range(3):m[r][c]=v[3+c*3+r]
 return m
def binding(q):return Quaternion((q[3],-q[0],-q[1],-q[2])).normalized().to_matrix()
def qts(v):
 m=Quaternion((v[3],v[0],v[1],v[2])).normalized().to_matrix().to_4x4();m.translation=Vector(v[4:7]);return m
def palm(j,t,k):
 a=Vector(j[t]['bindLocalQTS'][4:7]);b=Vector(j[k]['bindLocalQTS'][4:7]);x=(b-a).normalized();y=(a+b)/2;y=(y-x*y.dot(x)).normalized();z=x.cross(y)
 return Matrix((x,y,z)).transposed()
