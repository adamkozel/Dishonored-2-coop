"""Stage 8.4.1 (#237): generate outputs/d2-coop-lab/src/kiscule_policy.h from a Kiscule node-class classification.

The classification (one entry per arkKisculeNode* class: category WORLD / LOCAL-PLAYER / PRESENTATION / FLOW /
UNKNOWN, partner policy, vtable RVA from the executable's RTTI) is game-derived and stays local; the generated header
keeps only what the DLL needs: the vtable RVA, a short class name and the partner policy of every class that is not
plainly allowed. Usage:
    python -I tools/diag/gen_kiscule_policy.py <kiscule_class_policy.json>
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "outputs", "d2-coop-lab", "src", "kiscule_policy.h")
# LocalPlayer classes act on the player of the world that runs them, so the partner keeps running them in its own flow
# (hoststory-dunwall-v2015a: a host-replayed Cinematic left the partner stuck in the Mayhew scene). Only World classes
# are host-only; the five grant classes keep the older count mirror (kiscule_action_mirror.h).
MODES = {"WORLD": "World", "UNKNOWN": "World"}
# World classes that run in both worlds anyway:
# - ActionSpecialLoot places per-player items (items are per player, stage 8 brief). It attaches an item entity to an
#   NPC's loot, and Ramsey's ring is a different entity for Corvo and for Emily: blocked on the partner, the partner's
#   Ramsey never got the partner's ring (ring-onlyloot-v2023c failed, ring-onlyhealth-v2023c passed).
# - LevelTransition is coordinated by the mission-end mirror. Blocked on the partner, the request waited for plain
#   gameplay that the partner's ending cinematic never reached, and the partner sat in a black screen (boat-trace-v2024c).
# - Three classes do their work in their own vtable+0x38 step, which the native dispatcher (0x1407c0e30) calls after an
#   input handler that returns nonzero, as the host-story stub does: stubbing the handler never blocked them, and the
#   host's replay ran them a second time. ActionMidnightControl starts a midnight scene and Goto an NPC goto; a scene
#   that cannot start yet re-signals the node with input 0 (boat-trace-v2024c: 76 such retries, no input descriptor to
#   stub). Both are ambient NPC activity, which the host's NPC authority already decides, and a request would make the
#   host run the partner's ambient scene. EntitySpawnerControl spawns an entity in its step; running it host-only needs
#   the step skipped too (chapter 119, still to do).
BOTH_WORLDS = {"arkKisculeNodeActionSpecialLoot", "arkKisculeNodeLevelTransition", "arkKisculeNodeActionMidnightControl",
               "arkKisculeNodeGoto", "arkKisculeNodeEntitySpawnerControl"}


def main(path):
    data = json.load(open(path, encoding="utf-8"))
    rows = []
    for c in data["classes"]:
        mode = MODES.get(c["category"])
        policy = c.get("partner_policy", "")
        if c["category"] == "LOCAL-PLAYER" and policy.startswith("allow") or c["class"] in BOTH_WORLDS:
            mode = None
        if not mode or not c.get("vtable_rva"):
            continue
        name = c["class"].replace("arkKisculeNode", "")
        rows.append((int(c["vtable_rva"], 16), name, mode))
    rows.sort()
    lines = [
        "#pragma once",
        "// Stage 8.4.1 (#237): Kiscule node classes the partner must not run on its own, by node vtable RVA (from the",
        "// executable's RTTI). Generated by tools/diag/gen_kiscule_policy.py from the stage 8 classification (chapter 119):",
        "// World = writes the shared world (story flags, gameflow, usables, spawns, AI, transitions). Every other class",
        "// (local-player actions such as cinematics, teleports, grants and the diary; presentation; control flow; values)",
        "// runs in both worlds. LocalPlayer stays in the enum for a class a later area may route.",
        "#include <cstdint>",
        "#include <cstring>",
        "enum class KisculePolicy : std::uint8_t {Allow, World, LocalPlayer};",
        "struct KisculePolicyClass {std::uint32_t vtable; const char* name; KisculePolicy policy;};",
        "constexpr KisculePolicyClass kKisculePolicy[] = {",
    ]
    for rva, name, mode in rows:
        lines.append('    {0x%x, "%s", KisculePolicy::%s},' % (rva, name, mode))
    lines += [
        "};",
        "constexpr unsigned kKisculePolicyCount = sizeof(kKisculePolicy) / sizeof(kKisculePolicy[0]);",
        "// Sorted by vtable: binary search.",
        "inline int kisculePolicyIndex(std::uint32_t rva) {",
        "    unsigned lo = 0, hi = kKisculePolicyCount;",
        "    while (lo < hi) { const unsigned mid = (lo + hi) / 2; if (kKisculePolicy[mid].vtable < rva) lo = mid + 1; else hi = mid; }",
        "    return lo < kKisculePolicyCount && kKisculePolicy[lo].vtable == rva ? static_cast<int>(lo) : -1;",
        "}",
        "inline int kisculePolicyIndexByName(const char* name) {",
        "    for (unsigned i = 0; i < kKisculePolicyCount; ++i) if (!std::strcmp(kKisculePolicy[i].name, name)) return static_cast<int>(i);",
        "    return -1;",
        "}",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d classes (%d World, %d LocalPlayer)" % (OUT, len(rows), sum(r[2] == "World" for r in rows),
                                                              sum(r[2] == "LocalPlayer" for r in rows)))


if __name__ == "__main__":
    main(sys.argv[1])
