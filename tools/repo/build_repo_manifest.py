"""Selects the files that belong in the GitHub repository (Dishonored-2-coop).

Rules (decided 2026-10-14): mod source, build files, tooling, harness and
publisher scripts, handoff documentation, and small JSON/text evidence.
Never included: game copies (asset-game, lab-game), lab instances and save
profiles, builds, runtimes/tools, Ghidra project databases, game-derived
assets and release payloads, videos, movement banks and other binaries, and
the online-session take that contains the user's SteamID / friends list.

Usage: build_repo_manifest.py [--write files.txt] [--report]
"""
import os,sys,collections
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..'))
# Directory names excluded anywhere in the tree.
DIR_EXCLUDE={'asset-game','lab-game','lab-instances','build','asset-install-stage','animgen-feasibility',
    'node_modules','.venv','venv','__pycache__','.git','GameNetworkingSockets','Dishonored2-Debug','dist',
    'online-session-v1179','profile','bin','assets','files','research','.vs','Intermediate','Saved','DerivedDataCache',
    'tool-evaluation-2026-10-12'}
# Path prefixes (relative, forward slashes) excluded.
# sites/ is the separately published dashboard snapshot (own hosting metadata).
PREFIX_EXCLUDE=('outputs/d2-coop-lab/analysis/ghidra/input','sites/')
# Release folder: only its scripts and docs (handled by PREFIX_ALLOW_ONLY).
CODE={'.ps1','.psm1','.psd1','.py','.cjs','.js','.mjs','.ts','.h','.hpp','.hh','.inl','.cpp','.cc','.c','.cmake','.bat','.cmd','.java','.cs','.go','.sh'}
TEXT={'.md','.txt','.json','.log','.csv','.html','.css','.xml','.yml','.yaml','.ini','.cfg','.toml'}
NAMES={'CMakeLists.txt','.gitignore','.gitattributes','LICENSE','README','pre-commit'}
CAP_TEXT=256*1024       # data/text files above 256 KB stay local (sample dumps, big catalogs); keeps the repo ~0.5 GB
CAP_CODE=2*1024*1024
# Live project state updated after every result: tracked despite CAP_TEXT (up to CAP_DOCS).
# Keep in sync with LIVE in tools/repo/pre-commit.
LIVE={'work/current-task-state.json','work/natural-moveset/review-catalog.json'}
def wanted(rel,name,size):
    low=name.lower();ext=os.path.splitext(low)[1]
    if rel in LIVE:return size<=CAP_DOCS
    if rel.startswith('outputs/release/'):
        # Keep each package's installer, uninstaller, manifest and README only.
        return ext in {'.ps1','.md','.txt'} or low=='manifest.json' or low=='superseded.json'
    if any(rel.startswith(p) for p in PREFIX_EXCLUDE):return False
    if name in NAMES:return True
    if ext in CODE:return size<=CAP_CODE
    # The handoff documentation (53 MB, incl. large generated decompilation
    # chapters) is tracked whole; the cap applies to evidence data elsewhere.
    if ext in TEXT:return size<=(CAP_DOCS if rel.startswith('documentation/') else CAP_TEXT)
    return False
CAP_DOCS=16*1024*1024
GITIGNORE_BEGIN='# >>> generated by tools/repo/build_repo_manifest.py: allowed types kept local (size caps) >>>'
GITIGNORE_END='# <<< generated <<<'
def update_gitignore(oversized):
    # Root .gitignore re-includes (!*.json ...) beat .git/info/exclude, so the
    # oversized list lives in a marked section at the end of .gitignore.
    path=os.path.join(ROOT,'.gitignore');text=open(path,encoding='utf-8').read()
    if GITIGNORE_BEGIN in text:text=text[:text.index(GITIGNORE_BEGIN)].rstrip('\n')+'\n'
    lines=[GITIGNORE_BEGIN]+['/'+r.replace('[','\\[').replace(']','\\]') for r in sorted(oversized)]+[GITIGNORE_END]
    with open(path,'w',encoding='utf-8',newline='\n') as fh:fh.write(text+'\n'+'\n'.join(lines)+'\n')
    return len(oversized)
def walk():
    global oversized
    out=[];skipped=collections.Counter();skippedBytes=collections.Counter();oversized=[]
    for d,dirs,files in os.walk(ROOT):
        reld=os.path.relpath(d,ROOT).replace('\\','/');reld='' if reld=='.' else reld+'/'
        keep=[]
        for x in dirs:
            if x in DIR_EXCLUDE or x.endswith('.rep') or x.startswith('target-'):continue
            if reld=='work/' and x=='tools':continue  # Ghidra/MCP/tool installs (root tools/ is ours)
            # Archived source copies inside candidate folders and dashboard/script snapshots are
            # superseded by git history.
            if x=='src' and os.path.basename(d).startswith('candidate-'):continue
            if x.startswith('catalog-before-') or (x.startswith('before-') and 'movement-integration' in reld):continue
            # outputs/release keeps its package folders but never their payload ('files' is excluded above).
            keep.append(x)
        dirs[:]=keep
        for f in files:
            rel=reld+f;p=os.path.join(d,f)
            try:size=os.path.getsize(p)
            except OSError:continue
            if wanted(rel,f,size):out.append((rel,size))
            else:
                e=os.path.splitext(f.lower())[1] or '(none)';skipped[e]+=1;skippedBytes[e]+=size
                if e in CODE or e in TEXT:oversized.append(rel)
    return out,skipped,skippedBytes
if __name__=='__main__':
    files,skipped,skippedBytes=walk()
    total=sum(s for _,s in files)
    if '--report' in sys.argv or len(sys.argv)==1:
        by=collections.Counter();n=collections.Counter()
        for r,s in files:k='/'.join(r.split('/')[:2]);by[k]+=s;n[k]+=1
        print(f'INCLUDED {len(files)} files, {total/1048576:.1f} MB')
        for k,s in by.most_common(15):print(f'  {k:55} {s/1048576:8.1f} MB {n[k]:6}')
        print('LARGEST INCLUDED');[print(f'  {s/1048576:6.2f} MB {r}') for r,s in sorted(files,key=lambda x:-x[1])[:10]]
        print('SKIPPED (top by bytes)');[print(f'  {e:12} {skippedBytes[e]/1048576:10.1f} MB {skipped[e]:7}') for e,_ in skippedBytes.most_common(12)]
    if '--update-gitignore' in sys.argv:
        # Allowed file types that stay local (size caps) are listed in a
        # generated section of the root .gitignore so git status stays clean.
        print('gitignore oversized entries',update_gitignore([r for r in oversized if not r.startswith(PREFIX_EXCLUDE)]))
    if '--write' in sys.argv:
        path=sys.argv[sys.argv.index('--write')+1]
        with open(path,'w',encoding='utf-8',newline='\n') as fh:
            for r,_ in sorted(files):fh.write(r+'\n')
        print('wrote',path,len(files))
