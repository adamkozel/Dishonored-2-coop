"""Writes outputs/d2-coop-lab/src/inflate_test_vectors.h for d2_inflate_tests: zlib streams made by Python's zlib
(fixed and dynamic blocks, long overlapping matches) with their expected size and Adler-32. The tests build their
own multi-block stored stream."""
import random
import struct
import zlib
from pathlib import Path

random.seed(1310)
cases = [
    ('empty', b'', 6),
    ('one_byte', b'a', 6),
    ('fixed_short', b'Dishonored 2 co-op', 9),
    ('overlap_run', b'ab' * 20000, 9),
    ('text_dynamic', (b"The partner follows the host through every mission. " * 50) + bytes(range(256)) * 4, 9),
    ('floats', b''.join(struct.pack('<f', (i % 121) * 0.0125 + (i // 121) * 0.5) for i in range(8000)), 6),
]
out = ['// Generated by tools/release/make_inflate_vectors.py (Python zlib); do not edit.', '#pragma once', '#include <cstdint>', '#include <cstddef>', '']
names = []
for name, data, level in cases:
    packed = zlib.compress(data, level)
    out.append(f'const std::uint8_t {name}_packed[{max(len(packed), 1)}]={{' + ','.join(str(b) for b in packed) + '};')
    out.append(f'const std::size_t {name}_packed_size={len(packed)},{name}_size={len(data)};')
    out.append(f'const std::uint32_t {name}_adler=0x{zlib.adler32(data):08x}u;')
    names.append(name)
out.append('struct InflateVector{const char* name;const std::uint8_t* packed;std::size_t packedSize,size;std::uint32_t adler;};')
out.append('const InflateVector inflateVectors[]={' + ','.join(f'{{"{n}",{n}_packed,{n}_packed_size,{n}_size,{n}_adler}}' for n in names) + '};')
Path(__file__).resolve().parents[2].joinpath('outputs/d2-coop-lab/src/inflate_test_vectors.h').write_bytes(('\n'.join(out) + '\n').encode('utf-8'))
print('vectors', len(names))
